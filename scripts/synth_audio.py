# Vowel formants F1-F3 (Hz): Peterson and Barney (1952) adult-female means for /u/ (boot), /ɔ/ (bought), /ɑ/ (father).
# F4, F5 and all bandwidths are assumptions (typical synthesis values), not from that table.
VOWEL_F = np.array([[370.0, 950.0, 2670.0, 3300.0, 3850.0],
                    [590.0, 920.0, 2710.0, 3300.0, 3850.0],
                    [850.0, 1220.0, 2810.0, 3300.0, 3850.0]])
VOWEL_B = np.array([70.0, 90.0, 140.0, 180.0, 220.0])


def rosenberg(frac: np.ndarray, tp: float = 0.40, tn: float = 0.16) -> np.ndarray:
    u = np.zeros_like(frac)
    m = frac < tp
    u[m] = 0.5 * (1 - np.cos(np.pi * frac[m] / tp))
    m = (frac >= tp) & (frac < tp + tn)
    u[m] = np.cos(np.pi * (frac[m] - tp) / (2 * tn))
    return u


def voice(tl: TL, midi: np.ndarray, morph: np.ndarray, change_times: list[float], seed: int,
          vib_cents: float = 28.0) -> np.ndarray:
    """Sung vowel, unit RMS (mono, N). midi: f0 contour; morph: 0 = /u/, 1 = /ɔ/, 2 = /ɑ/."""
    rng = np.random.default_rng(seed)
    t = tl.t
    # delayed vibrato after each note change, rate made periodic over the loop
    c = np.sort(np.array(change_times) % tl.T) if change_times else np.array([0.0])
    idx = np.searchsorted(c, t, side="right") - 1
    last = np.where(idx >= 0, c[np.maximum(idx, 0)], c[-1] - tl.T)
    depth = vib_cents * np.clip((t - last - 0.08) / 0.35, 0, 1)
    vr = round(5.3 * tl.T) / tl.T
    jit = 0.004 * smooth_noise(rng, tl.N, 25.0)
    f0 = hz(midi + depth / 100.0 * np.sin(2 * np.pi * vr * t)) * (1 + jit)
    ph = periodic_phase(f0)
    u = rosenberg(ph % 1.0)
    shim = 1 + 0.05 * smooth_noise(rng, tl.N, 30.0)
    src = np.diff(u, prepend=u[-1]) * shim
    asp = circ_sos(hp(1500.0), rng.standard_normal(tl.N)) * u * 0.004
    src = src + asp
    # formant contour (log-interpolated between the three vowels)
    m = np.clip(morph, 0, 2)
    lo = np.minimum(m.astype(int), 1)
    w = m - lo
    F = np.exp(np.log(VOWEL_F[lo]) * (1 - w)[:, None] + np.log(VOWEL_F[lo + 1]) * w[:, None]).T  # (5, N)
    y = formant_cascade(src, F, VOWEL_B)
    y = circ_sos(lp(9000.0), y)
    return y / (np.sqrt(np.mean(y ** 2)) + 1e-12)


def formant_cascade(src: np.ndarray, F: np.ndarray, B: np.ndarray, block: int = 240) -> np.ndarray:
    pre = ns(0.4)
    y = np.concatenate([src[-pre:], src])
    Fx = np.concatenate([F[:, -pre:], F], axis=1)
    n = y.size
    for k in range(F.shape[0]):
        r = np.exp(-np.pi * B[k] / SR)
        out = np.empty_like(y)
        zi = np.zeros(2)
        for i0 in range(0, n, block):
            f = Fx[k, min(i0 + block // 2, n - 1)]
            a = np.array([1.0, -2 * r * np.cos(2 * np.pi * f / SR), r * r])
            out[i0:i0 + block], zi = signal.lfilter([a.sum()], a, y[i0:i0 + block], zi=zi)
        y = out
    return y[pre:]


def osc(tl: TL, midi: np.ndarray, harm: tuple[float, ...] = (1.0,), drive: float = 0.0) -> np.ndarray:
    """Periodic additive oscillator (sines at k f), optional tanh drive. Unit-ish peak."""
    ph = periodic_phase(hz(midi))
    y = sum(a * np.sin(2 * np.pi * (k + 1) * ph) for k, a in enumerate(harm))
    if drive > 0:
        y = np.tanh(drive * y) / np.tanh(drive)
    return y


def tom(rng: np.random.Generator, f_hi: float = 160.0, f_lo: float = 68.0, dur: float = 0.45) -> np.ndarray:
    n = ns(dur)
    t = np.arange(n) / SR
    f = f_lo + (f_hi - f_lo) * np.exp(-t / 0.035)
    y = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.11)
    click = signal.sosfilt(bp(1800.0, 5000.0), rng.standard_normal(n)) * np.exp(-t / 0.004) * 0.35
    y = y + click
    y[: ns(0.0008)] *= ramp(ns(0.0008))
    return y


def kick(rng: np.random.Generator, click: float = 0.3) -> np.ndarray:
    n = ns(0.5)
    t = np.arange(n) / SR
    f = 45.0 + 115.0 * np.exp(-t / 0.03)
    y = np.sin(2 * np.pi * np.cumsum(f) / SR) * np.exp(-t / 0.25) * (1 - np.exp(-t / (0.0007 if click else 0.003)))
    y += signal.sosfilt(bp(2500.0, 8000.0), rng.standard_normal(n)) * np.exp(-t / 0.003) * click
    return fade_edges(np.tanh(1.6 * y) / np.tanh(1.6), 0.0, 0.05)  # end fade: no truncation click at 0.5 s


def hat(rng: np.random.Generator, tau: float) -> np.ndarray:
    n = ns(tau * 6)
    t = np.arange(n) / SR
    y = signal.sosfilt(hp(7000.0, 4), rng.standard_normal(n)) * np.exp(-t / tau)
    return fade_edges(y, 0.0005, 0.002)


def clap(rng: np.random.Generator) -> np.ndarray:
    n = ns(0.3)
    t = np.arange(n) / SR
    nz = signal.sosfilt(bp(900.0, 2600.0), rng.standard_normal(n))
    env = sum(np.where(t >= d, np.exp(-(t - d) / 0.005), 0) for d in (0.0, 0.009, 0.018))
    env = env + 0.6 * np.where(t >= 0.027, np.exp(-(t - 0.027) / 0.06), 0)
    return fade_edges(nz * env, 0.0005, 0.01)


def pluck(midi: float, dur: float, fc: float, tau: float, wave: str = "saw", duty: float = 0.25,
          detune: float = 0.0, sub: float = 0.0) -> np.ndarray:
    """Filtered oscillator note: bright attack crossfading to the lowpassed body."""
    n = ns(dur)
    t = np.arange(n) / SR
    out = np.zeros(n)
    dets = (-detune, detune) if detune else (0.0,)
    for d in dets:
        f = np.full(n, hz(midi + d / 100.0))
        ph = np.cumsum(f) / SR + (0.37 if d > 0 else 0.0)
        out += (saw(ph, f) if wave == "saw" else pulse(ph, f, duty)) / len(dets)
    if sub:
        out += sub * np.sin(2 * np.pi * hz(midi) * t)
    env = np.exp(-t / tau)
    bright = signal.sosfilt(lp(fc * 3.0), out)
    dark = signal.sosfilt(lp(fc), out)
    w = np.exp(-t / 0.02)
    y = (dark + (bright - dark) * w) * env
    return fade_edges(y, 0.0015, 0.008)


def pad(chord: list[int], dur: float, fc: float, seed: int) -> np.ndarray:
    rng = np.random.default_rng(seed)
    n = ns(dur)
    t = np.arange(n) / SR
    y = np.zeros(n)
    for m in chord:
        for d in (-9.0, 0.0, 9.0):
            f = np.full(n, hz(m + d / 100.0))
            y += saw(np.cumsum(f) / SR + rng.random(), f)
    y = signal.sosfilt(lp(fc), y) / (3 * len(chord))
    y *= 1 + 0.15 * np.sin(2 * np.pi * 0.5 * t)
    return fade_edges(y, 0.25, 0.35)


# Free-free Euler-Bernoulli beam mode ratios: (beta_n L)^2 / (beta_1 L)^2 with beta_n L = 4.7300, 7.8532, 10.9956,
# 14.1372, 17.2788.
BAR = np.array([1.0, 2.7565, 5.4039, 8.9330, 13.3443])
BAR_AMP = np.array([1.0, 0.55, 0.36, 0.22, 0.14])


def strike(f: float, vel: float, rng: np.random.Generator, life: float | None = None) -> np.ndarray:
    """Struck metal bar: inharmonic modes with doublets, decay faster at higher frequency, mallet transient."""
    t60_1 = float(np.clip(3.4 * (f / 100.0) ** -0.35, 0.6, 4.0))
    dur = t60_1 * 1.05 if life is None else min(t60_1 * 1.05, life)
    n = ns(dur)
    t = np.arange(n) / SR
    y = np.zeros(n)
    for k, r in enumerate(BAR):
        fk = f * r
        if fk > 16000.0:
            break
        t60 = t60_1 / r ** 0.6
        a = BAR_AMP[k] * vel ** (0.35 * k)
        split = 1 + 0.0009 * (k + 1)
        e = np.exp(-6.91 * t / t60)
        y += a * e * (0.62 * np.sin(2 * np.pi * fk * t) + 0.38 * np.sin(2 * np.pi * fk * split * t + rng.random()))
    nt = ns(0.006)
    tr = signal.sosfilt(bp(2000.0, 9000.0), rng.standard_normal(nt)) * np.exp(-np.arange(nt) / (0.0009 * SR))
    y[:nt] += 0.25 * tr
    y *= vel
    y[: ns(0.0004)] *= ramp(ns(0.0004))
    return fade_edges(y, 0.0, 0.06 if life is not None else 0.2)


def mokugyo(rng: np.random.Generator, f0: float, vel: float) -> np.ndarray:
    """Hollow wooden temple block: a 1.5 ms mallet impulse (lowpassed noise) into three damped resonators.
    Mode ratios 1 : 1.58 : 2.73 and decays (tau 28 / 14 / 7 ms, i.e. about -40 dB at 130 ms for the body) are design
    choices for a woody, slightly pitched "tok" without metallic ring, not measured values."""
    n = ns(0.18)
    exc = np.zeros(n)
    m = ns(0.0015)
    exc[:m] = signal.sosfilt(lp(3500.0), rng.standard_normal(m)) * np.hanning(m)
    y = np.zeros(n)
    for ratio, tau, amp in [(1.0, 0.028, 1.0), (1.58, 0.014, 0.45), (2.73, 0.007, 0.25)]:
        f = f0 * ratio
        r = np.exp(-1.0 / (tau * SR))
        a = [1.0, -2 * r * np.cos(2 * np.pi * f / SR), r * r]
        y += amp * signal.lfilter([1.0 - r], a, exc)
    y += 0.15 * signal.sosfilt(bp(200.0, 400.0), exc) * 8  # a little hollow body thump
    y = y / (np.max(np.abs(y)) + 1e-12) * vel
    return fade_edges(y, 0.0003, 0.03)


def tock(rng: np.random.Generator) -> np.ndarray:
    n = ns(0.12)
    t = np.arange(n) / SR
    y = 0.8 * np.sin(2 * np.pi * 520 * t) * np.exp(-t / 0.022) + 0.4 * np.sin(2 * np.pi * 1380 * t) * np.exp(-t / 0.01)
    y += signal.sosfilt(bp(2000.0, 6000.0), rng.standard_normal(n)) * np.exp(-t / 0.002) * 0.3
    return fade_edges(y, 0.0004, 0.01)


# ---------------------------------------------------------------------------------------------------------------------
# Common reverb with segment gates (a gate kills the tail at a hard stop)
# ---------------------------------------------------------------------------------------------------------------------


def reverb(tl: TL, send: np.ndarray, ir: np.ndarray, splits: list[float], fade: float = 0.03) -> np.ndarray:
    """Convolution reverb on a loop. With splits, each segment's tail is cut `fade` s after the segment ends."""
    if not splits:
        return circ_conv(send, ir)
    sp = sorted(s % tl.T for s in splits)
    out = np.zeros((2, tl.N))
    nf = ns(fade)
    for i, a in enumerate(sp):
        b = sp[(i + 1) % len(sp)] + (tl.T if i + 1 == len(sp) else 0.0)
        ia, nl = int(round(a * SR)), int(round((b - a) * SR))
        seg = np.roll(send, -ia)[:nl].copy()
        e = min(ns(0.002), nl)
        seg[:e] *= ramp(e)
        seg[nl - e:] *= ramp(e)[::-1]
        for c in range(2):
            wet = signal.fftconvolve(seg, ir[c])[: nl + nf]
            wet[nl:] *= ramp(wet.size - nl)[::-1]
            idx = (ia + np.arange(wet.size)) % tl.N
            np.add.at(out[c], idx, wet)
    return out


