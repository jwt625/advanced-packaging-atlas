K1 = ([1.53512485958697, -2.69169618940638, 1.19839281085285], [1.0, -1.69065929318241, 0.73248077421585])
K2 = ([1.0, -2.0, 1.0], [1.0, -1.99004745483398, 0.99007225036621])


def lufs(x: np.ndarray) -> float:
    y = signal.lfilter(*K2, signal.lfilter(*K1, x, axis=1), axis=1)
    blk, hop = ns(0.4), ns(0.1)
    cs = np.concatenate([np.zeros((2, 1)), np.cumsum(y ** 2, axis=1)], axis=1)
    st = np.arange(0, y.shape[1] - blk + 1, hop)
    z = ((cs[:, st + blk] - cs[:, st]) / blk).sum(0)
    lk = -0.691 + 10 * np.log10(z + 1e-20)
    g = z[lk > -70]
    if g.size == 0:
        return -np.inf
    rel = -0.691 + 10 * np.log10(g.mean()) - 10
    g2 = z[(lk > -70) & (lk > rel)]
    return float(-0.691 + 10 * np.log10(g2.mean()))


def os_peak(x: np.ndarray) -> np.ndarray:
    """Per-sample peak of the 4x-oversampled signal (both channels), circular."""
    pad = 64
    xx = np.concatenate([x[:, -pad:], x, x[:, :pad]], axis=1)
    up = signal.resample_poly(xx, 4, 1, axis=1)[:, 4 * pad: 4 * (pad + x.shape[1])]
    return np.abs(up).reshape(2, x.shape[1], 4).max(axis=(0, 2))


def true_peak_db(x: np.ndarray) -> float:
    return float(20 * np.log10(os_peak(x).max() + 1e-12))


def limiter(x: np.ndarray, ceil_db: float) -> np.ndarray:
    ceil = 10 ** (ceil_db / 20)
    req = np.minimum(1.0, ceil / (os_peak(x) + 1e-12))
    size = ns(0.02) | 1
    g = ndimage.minimum_filter1d(req, size, mode="wrap")
    g = ndimage.uniform_filter1d(g, size, mode="wrap")
    return x * np.minimum(g, req)


def master(x: np.ndarray) -> tuple[np.ndarray, float]:
    y = x.copy()
    gain_db = 0.0
    for _ in range(6):
        d = TARGET_LUFS - lufs(y)
        gain_db += d
        y = limiter(y * 10 ** (d / 20), CEIL_DBTP)
        if abs(TARGET_LUFS - lufs(y)) < 0.05 and true_peak_db(y) <= CEIL_DBTP + 0.05:
            break
    return y, gain_db


def ffmpeg_loudness(path: Path) -> dict:
    r = subprocess.run(["ffmpeg", "-hide_banner", "-nostats", "-i", str(path), "-af",
                        "loudnorm=I=-16:TP=-1:LRA=11:print_format=json", "-f", "null", "-"],
                       capture_output=True, text=True, check=True)
    js = json.loads(r.stderr[r.stderr.rindex("{"): r.stderr.rindex("}") + 1])
    return {"I_LUFS": float(js["input_i"]), "TP_dBTP": float(js["input_tp"]), "LRA_LU": float(js["input_lra"])}


