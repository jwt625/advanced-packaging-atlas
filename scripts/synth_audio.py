# SFX cue level re the music in the cue's window (dB RMS); every cue sits under the music except the hero anneal.
CUE_TARGET_DB = {"sfx.boot": -14.0, "sfx.split": -18.0, "sfx.uf_hiss": -14.0, "sfx.uf_ticks": -7.0,
                 "sfx.tcb_tock": -4.0, "sfx.tcb_press": -7.0, "sfx.blips": -6.0, "sfx.thud": -4.0,
                 "sfx.anneal": 2.0, "sfx.hero_tick": -6.0}


def level_cues(tl: TL, music: np.ndarray, sfxl: dict[str, np.ndarray]) -> tuple[np.ndarray, dict[str, float]]:
    """Per-mix cue gains so each cue sits at CUE_TARGET_DB re the music."""
    gains = {}
    for c in cue_levels(tl, music, sfxl):
        d = CUE_TARGET_DB[c["cue"]] - c["sfx_minus_music_db"]
        gains[c["cue"]] = float(np.clip(d, -30.0, 12.0))
    out = sum(x * 10 ** (gains.get(k, 0.0) / 20) for k, x in sfxl.items())
    return out, gains


def hf_env_db(x: np.ndarray) -> np.ndarray:
    """2-16 kHz band, 10 ms RMS (dBFS), circular."""
    y = circ_sos(bp(2000.0, 16000.0, 4), x.mean(0))
    return 10 * np.log10(np.maximum(ndimage.uniform_filter1d(y ** 2, ns(0.01), mode="wrap"), 1e-14))


def bloom_env(tl: TL, x: np.ndarray) -> dict:
    """50 ms RMS at cut + 0.1 / 0.25 / 0.5 / 1.0 / 2.0 s, in dB relative to its peak within 0.8 s after the cut."""
    e = np.sqrt(np.maximum(ndimage.uniform_filter1d((x ** 2).mean(0), ns(0.05), mode="wrap"), 1e-20))
    t0 = tl["name"].start
    i0 = int(t0 * SR)
    k = i0 + int(np.argmax(e[i0: i0 + ns(0.8)]))
    out = {"peak_at_s": round(k / SR, 3)}
    for d in (0.1, 0.25, 0.5, 1.0, 2.0):
        j = min(i0 + ns(d), e.size - 1)
        out[f"cut+{d}s_db"] = round(float(20 * np.log10(e[j] / e[k])), 1)
    return out


def cut_check(tl: TL, mix: np.ndarray) -> dict:
    """At the name-card cut: 400 ms K-weighted loudness just before (window centred cut - 0.2 s) vs the loudest after
    (centres cut + 0.2 .. 1.2 s), and 2-16 kHz RMS (dBFS) before / after."""
    y = signal.lfilter(*K2, signal.lfilter(*K1, mix, axis=1), axis=1)
    e = -0.691 + 10 * np.log10(ndimage.uniform_filter1d((y ** 2).sum(0), ns(0.4)) + 1e-12)
    t0 = tl["name"].start
    hfb = circ_sos(bp(2000.0, 16000.0, 4), mix.mean(0))
    rms = lambda a, b: float(20 * np.log10(np.sqrt(np.mean(hfb[int(a * SR): int(b * SR)] ** 2)) + 1e-12))
    return {"lufs400_before_cut": round(float(e[int((t0 - 0.2) * SR)]), 1),
            "lufs400_after_cut_max": round(float(e[int((t0 + 0.2) * SR): int((t0 + 1.2) * SR)].max()), 1),
            "hf_2_16k_rms_dbfs_before_0p5s": round(rms(t0 - 0.5, t0), 1),
            "hf_2_16k_rms_dbfs_after_0p05_1s": round(rms(t0 + 0.05, t0 + 1.0), 1),
            "hf_2_16k_rms_dbfs_after_1_2s": round(rms(t0 + 1.0, t0 + 2.0), 1),
            **low_band_check(tl, mix)}


def low_band_check(tl: TL, mix: np.ndarray) -> dict:
    """20-450 Hz band at the cut: 200 ms RMS (dBFS) centred cut - 0.2 s vs the loudest centred cut + 0.1 .. 1.0 s,
    and the onsets detected in that band within 0.1 s of the cut."""
    t0 = tl["name"].start
    lb = circ_sos(bp(20.0, 450.0, 4), mix.mean(0))
    e = 10 * np.log10(ndimage.uniform_filter1d(lb ** 2, ns(0.2)) + 1e-20)
    return {"low_20_450_db_before": round(float(e[int((t0 - 0.2) * SR)]), 1),
            "low_20_450_db_after_peak": round(float(e[int((t0 + 0.1) * SR): int((t0 + 1.0) * SR)].max()), 1),
            "low_20_450_max_rise_db_per_50ms_near_cut": max_rise(lb, t0)}


def max_rise(x: np.ndarray, t0: float) -> float:
    """Fastest level increase (dB over 50 ms) of the 100 ms RMS envelope in [t0 - 0.1, t0 + 0.4] (100 ms spans two
    periods of the 32' E0 at 20.6 Hz); an onset shows as a jump of several dB, a 3 dB / 200 ms swell as ~0.75 dB."""
    m = x.mean(0) if x.ndim == 2 else x
    e = 10 * np.log10(ndimage.uniform_filter1d(m ** 2, ns(0.1)) + 1e-20)
    seg = e[int((t0 - 0.1) * SR): int((t0 + 0.4) * SR)]
    d = seg[ns(0.05):] - seg[: -ns(0.05)]
    return round(float(d.max()), 2)


def card_margin(tl: TL, mix: np.ndarray) -> dict:
    """Loudest K-weighted 400 ms on the name card vs in the hero (windows that do not straddle a cut)."""
    y = signal.lfilter(*K2, signal.lfilter(*K1, mix, axis=1), axis=1)
    e = -0.691 + 10 * np.log10(ndimage.uniform_filter1d((y ** 2).sum(0), ns(0.4)) + 1e-12)
    H, NM = tl["hero"], tl["name"]
    hm = float(e[int((H.start + 0.2) * SR): int((NM.start - 0.2) * SR)].max())
    cm = float(e[int((NM.start + 0.2) * SR): int((NM.start + min(0.9, NM.dur - 0.2)) * SR)].max())
    return {"hero_peak_400ms_lufs": round(hm, 1), "card_peak_400ms_lufs": round(cm, 1), "card_minus_hero_db": round(cm - hm, 1)}


def section_rates(tl: TL, kick_layer: np.ndarray, mix: np.ndarray) -> dict:
    """Onsets per second per section: the kick layer, and the 2-16 kHz band of the mix."""
    kon = detect_onsets(kick_layer)
    hon = detect_onsets(circ_sos(bp(2000.0, 16000.0, 4), mix.mean(0)))
    out = {}
    for name, shots in [("A", tl.section("a")), ("B", tl.section("b")), ("C", tl.section("c")),
                        ("M", tl.section("m"))]:
        if not shots:
            continue
        a, b = shots[0].start + 0.01, shots[-1].end - 0.01
        out[name] = {"window_s": [round(a - 0.01, 3), round(b + 0.01, 3)],
                     "kick_onsets_per_s": round(float(np.sum((kon >= a) & (kon < b)) / (b - a)), 2),
                     "hf_onsets_per_s": round(float(np.sum((hon >= a) & (hon < b)) / (b - a)), 2)}
    H, NM = tl["hero"], tl["name"]
    for k, a in enumerate(np.arange(H.start, NM.start - 1e-6, 2 * tl.spb)):
        b = min(a + 2 * tl.spb, NM.start)
        out[f"hero_{k + 1}"] = {"window_s": [round(float(a), 3), round(float(b), 3)],
                                "hf_onsets": int(np.sum((hon >= a - 0.01) & (hon < b - 0.01))),
                                "hf_onsets_per_s": round(float(np.sum((hon >= a - 0.01) & (hon < b - 0.01)) / (b - a)), 2)}
    return out


def name_cut_check(tl: TL, mix: np.ndarray) -> dict:
    """Broadband transient at the hero -> name-card cut: 2-16 kHz level around the cut vs the hero groove, and the
    strongest whole-mix spectral-flux onset near the cut relative to the hero's median onset."""
    t0 = tl["name"].start
    e = hf_env_db(mix)
    w = slice(int((t0 - 0.2) * SR), int((t0 + 0.2) * SR))
    ref = slice(int((t0 - 1.2) * SR), int((t0 - 0.2) * SR))
    after = slice(int((t0 + 0.02) * SR), int((t0 + 0.2) * SR))
    k = int(np.argmax(e[w]))
    lb = slice(int((t0 - tl.spb) * SR), int(t0 * SR))
    pb_ = slice(int((t0 - 2 * tl.spb) * SR), int((t0 - tl.spb) * SR))
    return {"hero_last_beat_hf_2_16k_max_dbfs": round(float(e[lb].max()), 1),
            "hero_beat_before_last_hf_2_16k_max_dbfs": round(float(e[pb_].max()), 1),
            "window_s": [round(t0 - 0.2, 3), round(t0 + 0.2, 3)],
            "hf_2_16k_max_dbfs_in_window": round(float(e[w].max()), 1),
            "at_s": round(t0 - 0.2 + k / SR, 3),
            "hf_2_16k_max_dbfs_hero_groove_before": round(float(e[ref].max()), 1),
            "hf_2_16k_max_dbfs_after_cut_0p02_0p2": round(float(e[after].max()), 1)}


def hf_pulse_start(tl: TL, mix: np.ndarray) -> dict:
    """High-band (2-16 kHz) onsets around the l1a cut."""
    y = circ_sos(bp(2000.0, 16000.0, 4), mix.mean(0))
    on = detect_onsets(y)
    t0 = tl.section("a")[0].start
    sel = on[(on > t0 - 0.3) & (on < t0 + 1.0)]
    return {"l1a_cut_s": t0, "hf_onsets_s": [round(float(x), 3) for x in sel],
            "first_hf_onset_at_or_after_cut_s": round(float(sel[sel >= t0 - 0.02][0]), 3) if np.any(sel >= t0 - 0.02) else None}


def cue_levels(tl: TL, music: np.ndarray, sfxl: dict[str, np.ndarray]) -> list[dict]:
    """RMS of each SFX cue vs the music around it (music window at least 0.3 s, centred on the cue window)."""
    win = {"sfx.boot": ("close", float(EVENTS["close"]["contact"]), float(EVENTS["close"]["contact"]) + 0.5),  # type: ignore[arg-type]
           "sfx.split": ("open", float(EVENTS["open"]["split"]), float(EVENTS["open"]["split_done"])),  # type: ignore[arg-type]
           "sfx.uf_hiss": ("l2a", 0.2, 1.9), "sfx.uf_ticks": ("l2a", 0.3, 2.0),
           "sfx.tcb_tock": ("l4a", 0.79, 0.84), "sfx.tcb_press": ("l4a", 0.95, 1.6), "sfx.blips": ("l1b", 0.18, 0.4),
           "sfx.thud": ("l1b", 0.385, 0.5), "sfx.anneal": ("hero", 0.55, 1.2),  # the E5 half
           "sfx.hero_tick": ("hero", 0.87, 0.89)}
    out = []
    for k, (sid, a, b) in win.items():
        s = tl.es(sid)
        a, b = a / s.speed, min(b / s.speed, s.dur)  # windows are in scene time
        if k not in sfxl or b <= a or not np.any(sfxl[k][:, int((s.start + a) * SR): int((s.start + b) * SR)]):
            continue
        sl = slice(int((s.start + a) * SR), int((s.start + b) * SR))
        c, h = s.start + (a + b) / 2, max(b - a, 0.3) / 2
        ml = (np.arange(int((c - h) * SR), int((c + h) * SR))) % tl.N
        rs = np.sqrt(np.mean(sfxl[k][:, sl] ** 2)) + 1e-12
        rm = np.sqrt(np.mean(music[:, ml] ** 2)) + 1e-12
        out.append({"cue": k, "window": f"{sid}+{a}-{b}", "sfx_minus_music_db": round(float(20 * np.log10(rs / rm)), 1)})
    return out


