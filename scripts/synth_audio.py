# V2 alternatives: a long harmonic build peaking on the name card (owner, 2026-10-22). Each is the plan-of-record V2
# groove plus one harmonic layer whose level follows ramp_db(); the hero is the top of the ramp, the card the peak.
# ---------------------------------------------------------------------------------------------------------------------


def ramp_db(tl: TL, mk: dict, tau: float | None = None, attack: float = 0.05) -> np.ndarray:
    """Loop-periodic level contour (dB) of the harmonic layer: rising through the sections, top in the hero, peak on
    the name card, hold, then down through the close to the open's level. With tau (s): a short bloom instead of the
    hold: 50 ms rise from the cut to the peak, exponential decay (linear in dB, 8.686 / tau dB/s) to -30 dB, then a
    quiet tail."""
    if tau:
        t30 = 30.0 * tau / 8.686
        return periodic(tl, [(0.0, -36.0), (mk["a0"], -32.0), (mk["b0"], -24.0), (mk["c0"], -17.0), (mk["m0"], -12.0),
                             (mk["H"], -11.0), (mk["NM"] - 0.02, -7.0), (mk["NM"] + attack, 0.0),
                             (mk["NM"] + attack + t30, -30.0), (max(mk["CL"], mk["NM"] + attack + t30 + 0.05), -31.0),
                             (max(mk["cc"], mk["NM"] + attack + t30 + 0.1), -33.0), (tl.T - 1e-3, -36.0)])
    return periodic(tl, [(0.0, -36.0), (mk["a0"], -32.0), (mk["b0"], -24.0), (mk["c0"], -17.0), (mk["m0"], -12.0),
                         (mk["H"], -11.0), (mk["NM"] - 0.02, -7.0), (mk["NM"] + 0.05, 0.0), (mk["NM"] + 0.9, -1.5),
                         (mk["CL"], -12.0), (mk["cc"], -26.0), (tl.T - 1e-3, -36.0)])


def progress(tl: TL, mk: dict) -> np.ndarray:
    """Build progress: 0 at the open, 0.55-0.65 through the hero, 1 on the name card (it opens there), back to 0 over
    the close (piecewise linear)."""
    return periodic(tl, [(0.0, 0.0), (mk["a0"], 0.05), (mk["b0"], 0.25), (mk["c0"], 0.4), (mk["m0"], 0.5),
                         (mk["H"], 0.55), (mk["NM"] - 0.02, 0.65), (mk["NM"] + 0.15, 1.0), (mk["NM"] + 0.9, 1.0),
                         (mk["cc"], 0.2), (tl.T - 1e-3, 0.0)])


def harm_additive(tl: TL, harmony: list, mk: dict, seed: int, fast_card: bool = False,
                  soft_card: bool = False) -> np.ndarray:
    """A: vowel-like additive pad on the chord tones (one octave below the arp register): harmonic count 3 -> 40,
    spectral tilt -10 -> -4 dB/oct, formant envelope /u/ -> /ɑ/ (Peterson and Barney means, VOWEL_F) as the build
    progresses; 4 cents chorus."""
    rng = np.random.default_rng(seed)
    pr = progress(tl, mk)
    K = 3 + 37 * pr
    tilt = 1.66 - 1.0 * pr  # amplitude ~ k^-tilt: 1.66 -> -10 dB/oct, 0.66 -> -4 dB/oct
    morph = 2.0 * pr
    bus = Bus(tl)
    for a, b, tones in harmony:
        card = a >= mk["NM"] - 1e-3
        ends_at_card = abs(b - mk["NM"]) < 1e-3
        if soft_card and card:
            continue  # nothing new enters at the cut: the continuous low pedal (low_pedal) carries the card
        # soft card (owner, 2026-10-23): the segment before the card ends at the cut (60 ms release, no bright carry-
        # over); the card chord is low register only (two octaves down, partials under ~450 Hz), 200 ms attack
        d = b - a if (soft_card and ends_at_card) else b - a + 0.4
        n = ns(d)
        idx = (int(round(a * SR)) + np.arange(n)) % tl.N
        t = np.arange(n) / SR
        kk, tl_, mo = K[idx], tilt[idx], np.clip(morph[idx], 0, 2)
        lo = np.minimum(mo.astype(int), 1)
        w = mo - lo
        F = np.exp(np.log(VOWEL_F[lo]) * (1 - w)[:, None] + np.log(VOWEL_F[lo + 1]) * w[:, None])[:, :3]
        y = np.zeros(n)
        for m in tones:
            f0 = float(hz(m - 24 if (soft_card and card) else m - 12))
            fmax = 2000.0 + 10000.0 * np.clip(pr[idx], 0, 1) ** 3  # brightness opens fully on the card
            if soft_card and card:
                fmax = np.full(n, 450.0)
            for k in range(1, 41):
                fk = k * f0
                if fk > 12000.0:
                    break
                gate = np.clip(kk - k + 1, 0, 1) * np.clip((fmax - fk) / 500.0 + 1, 0, 1)
                if not np.any(gate):
                    continue
                fe = 0.25 + sum(np.exp(-0.5 * ((fk - F[:, i]) / bw) ** 2) for i, bw in enumerate((140.0, 200.0, 300.0)))
                amp = gate * k ** (-tl_) * fe
                for det in (-4.0, 4.0):
                    y += 0.5 * amp * np.sin(2 * np.pi * fk * 2 ** (det / 1200) * t + rng.random() * 2 * np.pi)
        att = 0.04 if fast_card and card else 0.15  # the card chord blooms at the cut
        rel = 0.35
        if soft_card and card:
            att = 0.2
        if soft_card and ends_at_card:
            rel = 0.06
        bus.add(fade_edges(y / np.sqrt(len(tones)), att, rel), a)
    return bus.x


def harm_voicing(tl: TL, harmony: list, mk: dict, seed: int) -> np.ndarray:
    """B: chord voicing that grows upward with the sections (2 -> 3 -> 4 -> 5 -> 6 voices; only the card adds the low
    root under its full spread chord) as a
    detuned-saw pad whose lowpass stays dark (about 1.0-1.3 kHz in the hero, under the arps) and opens to 6 kHz on
    the card."""
    bus = Bus(tl)
    pr = progress(tl, mk)
    for a, b, tones in harmony:
        r = tones[0] - 12  # chord root, octave 3
        third, fifth = tones[1] - 12, tones[2] - 12
        if a < mk["b0"] - 1e-6:
            v = [r, fifth]
        elif a < mk["c0"] - 1e-6:
            v = [r, third, fifth]
        elif a < mk["m0"] - 1e-6:
            v = [r, third, fifth, r + 12]
        elif a < mk["H"] - 1e-6:
            v = [r, third, fifth, r + 12, third + 12]
        elif a < mk["NM"] - 1e-6:
            v = [r, third, fifth, r + 12, third + 12, fifth + 12]
        else:  # the card: full spread of its chord
            c = sorted(tones)
            v = [c[0] - 12, c[0], c[1], c[2], c[0] + 12, c[1] + 12, c[2] + 12, c[0] + 24]
        fc = float(900.0 + 5100.0 * pr[int(round(a * SR)) % tl.N] ** 6)
        bus.add(pad(v, b - a + 0.4, fc, seed=seed + int(a * 100)) * (3.0 / np.sqrt(len(v))), a)
    return bus.x


PEDAL = [40, 47, 52]  # E2 B2 E3: a low E pedal, consonant over the hero's C and D and the card's E minor


def low_pedal(tl: TL, mk: dict, seed: int, bump_db: float = 3.0, tau: float = 0.5) -> np.ndarray:
    """Continuous low pedal (owner, 2026-10-23): fades in over the second before the hero, plays under the groove
    through the hero, runs across the name-card cut without re-attack, is bumped +bump_db there with a 200 ms rise,
    then decays (tau) into the quiet tail. Partials of E2 / B2 / E3 under 450 Hz, gentle tilt, slow chorus."""
    rng = np.random.default_rng(seed)
    t0, t1 = mk["H"] - 1.0, mk["cc"] + 0.3
    n = ns(t1 - t0)
    t = np.arange(n) / SR
    y = np.zeros(n)
    for m in PEDAL:
        f0 = float(hz(m))
        for k in range(1, 12):
            fk = k * f0
            if fk > 450.0:
                break
            a = k ** -1.2 * np.clip((450.0 - fk) / 100.0, 0, 1)
            for det in (-3.0, 3.0):
                y += 0.5 * a * np.sin(2 * np.pi * fk * 2 ** (det / 1200) * t + rng.random() * 2 * np.pi)
    t30 = 30.0 * tau / 8.686
    pk = mk["NM"] + 0.2
    env_db = np.interp(t0 + t, [t0, mk["H"], mk["NM"], pk, pk + t30, max(mk["CL"], pk + t30 + 0.05), mk["cc"], t1],
                       [-45.0, 0.0, 0.0, bump_db, bump_db - 30.0, bump_db - 31.0, bump_db - 34.0, -60.0])
    bus = Bus(tl)
    bus.add(fade_edges(y * 10 ** (env_db / 20), 0.05, 0.05) / np.sqrt(len(PEDAL)), t0)
    return bus.x


EMIN_STACK = [40, 47, 52, 55, 59, 62, 64, 67, 69, 71, 74, 76, 79, 83, 86, 88]  # E2 B2 E3 G3 B3 D4 E4 G4 A4 B4 D5 ...


def harm_bloom(tl: TL, mk: dict, seed: int) -> np.ndarray:
    """C: E minor pentatonic stack that thickens with each section's cut-rate doubling (2 / 4 / 6 / 8 / 11 / 16
    voices for open / A / B / C / M / hero), every voice a soft sine with 2nd / 3rd partials and a slow chorus;
    the card holds all 16 as the open resolution, the close releases them from the top down."""
    rng = np.random.default_rng(seed)
    counts = [(0.0, 2), (mk["a0"], 4), (mk["b0"], 6), (mk["c0"], 8), (mk["m0"], 11), (mk["H"], 16)]
    bus = Bus(tl)
    nv = len(EMIN_STACK)
    for i, m in enumerate(EMIN_STACK):
        on = next(t for t, c in counts if c > i)
        off = mk["NM"] + 0.9 + (mk["cc"] - mk["NM"] - 0.9) * (1 - i / (nv - 1))  # top voices release first
        if i < 2:  # the two lowest voices run through the loop
            amp = np.ones(tl.N)
            ph = periodic_phase(np.full(tl.N, float(hz(m))))
            ph2 = periodic_phase(np.full(tl.N, float(hz(m)) * 1.0015))
            y = (np.sin(2 * np.pi * ph) + np.sin(2 * np.pi * ph2)) * 0.5
            y += 0.3 * np.sin(4 * np.pi * ph) + 0.1 * np.sin(6 * np.pi * ph)
            bus.x += pan2(y * amp * 0.6, 0.0)
            continue
        d = off - on + 0.6
        n = ns(d)
        t = np.arange(n) / SR
        f = float(hz(m))
        p0 = rng.random() * 2 * np.pi
        y = 0.5 * (np.sin(2 * np.pi * f * t + p0) + np.sin(2 * np.pi * f * 1.0015 * t + p0 + 1.0))
        y += 0.3 * np.sin(4 * np.pi * f * t) + 0.1 * np.sin(6 * np.pi * f * t)
        g = 0.6 * (1.0 - 0.025 * i)
        bus.add(fade_edges(y, 0.4, 0.6), on, gain=g, pan=float(np.clip((i - nv / 2) / nv, -0.5, 0.5)))
    return bus.x


