def v2_alt(variant: str):  # type: ignore[no-untyped-def]
    def build(tl: TL, reg: Reg) -> dict[str, np.ndarray]:
        cfg = ALTS[variant]
        o = dict(cfg["opts"])
        name = f"v2_alt_{variant}"
        if "lift" in o:
            SC = tl.section("c")
            o["shift"] = [(SC[0].start if SC else tl["hero"].start, tl["name"].start, o.pop("lift"))]
        n0 = len(reg.items)
        base = v2(tl, reg, o)
        for it in reg.items[n0:]:
            it["layer"] = it["layer"].replace("v2.", f"{name}.", 1)
        mk = o["_marks"]
        tau = cfg.get("bloom_tau")
        soft = bool(cfg.get("soft_card"))
        if cfg["layer"] == "organ":
            st = cfg.get("top_step")  # (seconds after the hero cut, [(old midi, new midi), ...])
            steps = [(mk["H"] + st[0], m1, m2) for m1, m2 in st[1]] if st else None
            hv = cfg.get("hero_voice")  # extra key per hero chord, keyed by the chord's root pitch class
            harm = o["_harmony"]
            if hv:
                pcs = {0: "C", 2: "D", 4: "E", 7: "G"}
                harm = [(a, b, tones + [hv[pcs[tones[0] % 12]]] if (mk["H"] - 1e-3 <= a < mk["NM"] - 1e-3
                                                                    and pcs.get(tones[0] % 12) in hv) else tones)
                        for a, b, tones in harm]
            vmc = cfg.get("hero_voice_mod")
            vmod = {"t0": mk["H"], "t1": mk["NM"], **vmc} if vmc else None
            h = harm_organ(tl, harm, mk, seed=505, steps=steps, voice_mod=vmod)
        elif cfg["layer"] == "additive":
            h = harm_additive(tl, o["_harmony"], mk, seed=501, fast_card=bool(tau) and not soft, soft_card=soft)
        elif cfg["layer"] == "voicing":
            h = harm_voicing(tl, o["_harmony"], mk, seed=502)
        else:
            h = harm_bloom(tl, mk, seed=503)
        h = h * 10 ** (ramp_db(tl, mk, tau, cfg.get("card_attack", 0.05)) / 20)
        # level: bisect the layer gain so that the card's loudest 400 ms (K-weighted) sits card_db above the hero's
        # loudest 400 ms, measured on the full mix (groove + layer + its reverb + the SFX as levelled for this mix)
        music = sum(base.values())
        ir = make_ir(11, 1.2, 1.6) if tau else make_ir(11, 2.4, 3.0)  # short room for a short bloom
        if cfg["layer"] == "organ":  # cathedral: full-band tail gated at the cut, its low part (< 600 Hz) rings on
            ir_c = make_ir(12, 3.2, 4.0, bright_tau=0.12, predelay=0.03)
            hm = h.mean(0)
            h = h + reverb(tl, hm, ir_c, [mk["NM"]], fade=0.1) * 0.16
            tail = circ_conv(circ_sos(lp(600.0, 4), hm), ir_c) * 0.16
            post = np.clip((tl.t - mk["NM"]) / 0.1, 0, 1) * (tl.t < mk["CL"] + 1.0)
            h = h + tail * post
        elif soft:  # the hero layer's reverb tail is gated at the cut: nothing bright rings into the card
            h = h + reverb(tl, h.mean(0), ir, [mk["NM"]], fade=0.08) * 0.12
        else:
            h = h + circ_conv(h.mean(0), ir) * (0.12 if tau else 0.25)
        kw = lambda x: signal.lfilter(*K2, signal.lfilter(*K1, x, axis=1), axis=1)
        sfx_l = sfx(tl, Reg(), organ=name in ORGAN_SFX)  # the SFX as levelled in the mix (the hero anneal adds several dB to the hero); the
        sv, _ = level_cues(tl, music, sfx_l)  # alternatives level them against the groove, as in the plan of record
        w4 = ns(0.4)
        hs, he = int(mk["H"] * SR), int((mk["NM"] - 0.2) * SR)  # 400 ms windows that do not straddle the cut
        cs, ce = int((mk["NM"] + 0.2) * SR), int((mk["NM"] + 0.9) * SR)

        def margin(gdb: float) -> float:
            m = music + h * 10 ** (gdb / 20)
            e = ndimage.uniform_filter1d((kw(m + sv) ** 2).sum(0), w4)
            if soft:  # loudest 400 ms after the cut (windows centred NM+0.2 .. NM+1.2) vs the 400 ms just before it
                return 10 * np.log10(e[cs: int((mk["NM"] + 1.2) * SR)].max() / e[int((mk["NM"] - 0.2) * SR)])
            return 10 * np.log10(e[cs:ce].max() / e[hs:he].max())

        if "organ_gain_db" in cfg:  # fixed: the organ level of the last approved render
            hi = float(cfg["organ_gain_db"])
        elif cfg["layer"] == "organ":  # match A's additive layer (K-weighted RMS from the open to the cut)
            ref = harm_additive(tl, o["_harmony"], mk, seed=501, soft_card=True)
            ref = ref * 10 ** (ramp_db(tl, mk, tau, cfg.get("card_attack", 0.05)) / 20)
            ref = (ref + reverb(tl, ref.mean(0), ir, [mk["NM"]], fade=0.08) * 0.12) * 10 ** (cfg["harm_gain_db"] / 20)
            i0, i1 = int(mk["a0"] * SR), int(mk["NM"] * SR)
            hi = float(20 * np.log10(np.sqrt(np.mean(kw(ref)[:, i0:i1] ** 2)) / np.sqrt(np.mean(kw(h)[:, i0:i1] ** 2))))
        elif "harm_gain_db" in cfg:  # fixed: keeps the build exactly as in the last reviewed render
            hi = float(cfg["harm_gain_db"])
        else:
            lo, hi = -20.0, 40.0
            for _ in range(30):
                mid = (lo + hi) / 2
                lo, hi = (mid, hi) if margin(mid) < cfg["card_db"] else (lo, mid)
        g = 10 ** (hi / 20)
        log(f"{name}: harmonic layer '{cfg['layer']}' gain {hi:+.1f} dB"
            + ("" if soft else f" (card 400 ms {margin(hi):+.1f} dB re the hero peak, before mastering)"))
        out = {k.replace("v2.", f"{name}.", 1): x for k, x in base.items()}
        out[f"{name}.harm"] = h * g
        if soft:
            # continuous low pedal: its level is set so the 20-450 Hz band rises by low_rise_db across the cut
            # (200 ms RMS centred cut - 0.2 s vs the loudest 200 ms RMS centred cut + 0.1 .. 1.0 s)
            if cfg.get("pedal") == "organ":
                ped = organ_pedal(tl, mk, seed=506, bump_db=cfg.get("pedal_bump_db", cfg.get("bump_db", 3.0)),
                                  tau=tau or 0.5, early=bool(cfg.get("pedal_early")), contra_db=cfg.get("contra_db"))
                ir_p = make_ir(13, 3.2, 4.0, bright_tau=0.12, predelay=0.03)
                ped = ped + circ_conv(ped.mean(0), ir_p) * 0.15
            else:
                ped = low_pedal(tl, mk, seed=504, bump_db=cfg.get("bump_db", 3.0), tau=tau or 0.5)
            lowb = lambda x: circ_sos(bp(20.0, 450.0, 4), x.mean(0))
            rest = lowb(music + out[f"{name}.harm"] + sv)
            lp_ = lowb(ped)
            w2 = ns(0.2)
            ib, ia0, ia1 = int((mk["NM"] - 0.2) * SR), int((mk["NM"] + 0.1) * SR), int((mk["NM"] + 1.0) * SR)

            def rise(gdb: float) -> float:
                e = ndimage.uniform_filter1d((rest + lp_ * 10 ** (gdb / 20)) ** 2, w2)
                return 10 * np.log10(e[ia0:ia1].max() / e[ib])

            if "pedal_gain_db" in cfg:  # fixed: the pedal level of the last approved render
                hi = float(cfg["pedal_gain_db"])
            else:
                lo, hi = -40.0, 30.0
                for _ in range(30):
                    mid = (lo + hi) / 2
                    lo, hi = (mid, hi) if rise(mid) < cfg.get("low_rise_db", 2.0) else (lo, mid)
            out[f"{name}.pedal"] = ped * 10 ** (hi / 20)
            log(f"{name}: low pedal gain {hi:+.1f} dB (20-450 Hz rise across the cut {rise(hi):+.1f} dB)")
        return out

    return build


