def v1(tl: TL, reg: Reg) -> dict[str, np.ndarray]:
    pa, pb = tl.pa(), tl.pb()
    H, NM = tl["hero"], tl["name"]
    lg = tl.ev("hero", "line_gone")
    cu = tl.ev("hero", "cu_contact")
    cc = tl.ev("close", "contact")
    rng = np.random.default_rng(101)
    # lead: E major pentatonic, one degree per pitch level; pass B one degree above pass A
    ladA = [56, 59, 61, 64, 66, 68, 71]   # G#3 B3 C#4 E4 F#4 G#4 B4
    ladB = [59, 61, 64, 66, 68, 71, 73]   # B3 .. C#5
    ch = [(0.0, 59.0)] + [(s.start, float(m)) for s, m in zip(pa, ladA)] + [(s.start, float(m)) for s, m in zip(pb, ladB)]
    ch += [(H.start, 76.0), (NM.start, 64.0), (cc, 59.0)]
    midi = steps(tl, ch, 0.06)
    prev = ch[-1][1]
    for tc, m in sorted(ch):
        if m != prev:
            reg.add(tc, f"lead {note_name(int(prev))}->{note_name(int(m))}", "v1.lead", "pitch", m0=prev, m1=m)
        prev = m
    morph = periodic(tl, [(0.0, 0.0), (pa[0].start, 0.0), (pa[-1].end, 0.8), (pb[-1].end, 1.6), (cu, 2.0),
                          (NM.start + 0.3, 2.0), (cc, 0.4), (tl.T - 1e-3, 0.0)])
    lead = voice(tl, midi, morph, [c[0] for c in ch], seed=11)
    amp = periodic(tl, [(0.0, 0.7), (pa[0].start, 0.75), (pa[-1].end, 0.8), (pb[-1].end, 0.9), (H.start + 0.1, 0.97),
                        (NM.start - 0.004, 1.0), (NM.start + 0.004, 0.0), (NM.start + 0.12, 0.0),
                        (NM.start + 0.35, 0.5), (NM.end, 0.38), (cc, 0.18), (tl.T - 1e-3, 0.7)])
    lead = lead * amp * 0.12
    # choir: A major (A4 C#5 under E5) in the hero, B sus4 (F#4 B4 E5) once the interface line is gone
    choir = np.zeros(tl.N)
    camp = periodic(tl, [(H.start - 0.01, 0.0), (H.start + 0.25, 0.15), (cu, 0.35), (NM.start - 0.004, 0.6),
                         (NM.start + 0.004, 0.0)])
    for i, (m0, m1) in enumerate([(69.0, 66.0), (73.0, 71.0)]):
        cm = steps(tl, [(H.start - 0.5, m0), (lg, m1), (NM.start + 0.5, m0)], 0.08)
        choir += voice(tl, cm, np.minimum(morph + 0.2 * i, 2.0), [H.start, lg], seed=21 + i, vib_cents=22.0)
        reg.add(lg, f"choir {note_name(int(m0))}->{note_name(int(m1))}", f"v1.choir{i}", "info")
    choir = choir * camp * 0.08
    # sub: E1 crescendo (dB-linear), roots move in pass B and the hero, hard stop, soft return under the name card footnote
    roots = [(0.0, 28.0)] + [(s.start, float(r)) for s, r in zip(pb, [28, 28, 28, 25, 25, 33, 33])]
    roots += [(H.start, 33.0), (lg, 35.0), (NM.start + 0.2, 28.0)]
    sub = osc(tl, steps(tl, roots, 0.03), (1.0, 0.45, 0.12), drive=1.4)
    sdb = periodic(tl, [(0.0, -32.0), (pa[0].start, -28.0), (pb[0].start, -14.0), (NM.start - 0.004, 0.0),
                        (NM.start + 0.004, -90.0), (NM.start + 0.3, -90.0), (NM.start + 0.65, -15.0),
                        (cc, -22.0), (tl.T - 1e-3, -32.0)])
    sub = sub * 10 ** (sdb / 20) * 0.42
    reg.add(NM.start, "hard stop", "v1.music", "stop")
    # pulse: density accelerates; accents on the cuts
    hits: list[tuple[float, float]] = []
    for i, s in enumerate(pa):
        step = 1.0 if i < 4 else 0.5
        hits += [(t, 1.0 if j == 0 else 0.55) for j, t in enumerate(local_grid(s.start, s.end, step))]
    for i, s in enumerate(pb):
        step = 0.25 if i < 3 else 0.125
        hits += [(t, 1.0 if j == 0 else 0.5) for j, t in enumerate(local_grid(s.start, s.end, step))]
    hits.append((H.start, 1.0))
    hits += [(t, 0.5) for t in local_grid(cu, lg, 0.125)]
    t, iv = lg, 0.125
    while t < NM.start - 0.03:
        hits.append((t, 0.6 + 0.4 * (t - lg) / (NM.start - lg)))
        t += iv
        iv = max(0.05, iv * 0.93)
    vel_env = periodic(tl, [(0.0, 0.6), (pa[0].start, 0.6), (pb[0].start, 0.75), (NM.start - 0.01, 1.0),
                            (NM.start + 0.01, 0.3)])
    pbus = Bus(tl)
    for t, v in hits:
        g = v * vel_env[min(int(t * SR), tl.N - 1)]
        f_hi = 175.0 if v >= 1.0 else 150.0
        pbus.add(tom(rng, f_hi=f_hi), t, gain=0.5 * g, until=NM.start)
        if v >= 1.0:
            reg.add(t, "pulse accent", "v1.pulse")
    puls = pbus.x
    # reverb, gated at the name card so the stop is hard
    ir = make_ir(7, 2.4, 3.0)
    wet = reverb(tl, lead + choir + 0.08 * puls.mean(0), ir, [NM.start]) * 0.22
    return {"v1.lead": pan2(lead, 0.0), "v1.choir": pan2(choir, 0.0) * 1.0, "v1.sub": pan2(sub, 0.0),
            "v1.pulse": puls, "v1.wet": wet}


def local_grid(t0: float, t1: float, step: float, guard: float = 0.03) -> list[float]:
    out, k = [], 0
    while t0 + k * step < t1 - guard:
        out.append(t0 + k * step)
        k += 1
    return out


