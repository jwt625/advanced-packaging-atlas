F0_LADDER = 82.40689  # E2: 1 mm
A_LADDER = float(np.log(16.0) / np.log(1000.0 / 0.4))  # 0.4 um -> 4 octaves above
EMIN_PENT = {4, 7, 9, 11, 2}


def material_ladder() -> list[dict]:
    rows = []
    cand = [m for m in range(24, 100) if m % 12 in EMIN_PENT]
    for k, p in LEVEL_PITCH_UM.items():
        f = F0_LADDER * (1000.0 / p) ** A_LADDER
        m_raw = 69 + 12 * np.log2(f / 440.0)
        mq = min(cand, key=lambda m: abs(m - m_raw))
        rows.append({"level": k, "pitch_um": p, "f_raw": round(float(f), 2), "midi": mq, "note": note_name(mq),
                     "f_q": round(float(hz(mq)), 2), "cents": round(float((mq - m_raw) * 100), 1)})
    return rows


def v3(tl: TL, reg: Reg) -> dict[str, np.ndarray]:
    pa, pb = tl.pa(), tl.pb()
    H, NM = tl["hero"], tl["name"]
    lg, cu = tl.ev("hero", "line_gone"), tl.ev("hero", "cu_contact")
    cc = tl.ev("close", "contact")
    spb = tl.spb
    rng = np.random.default_rng(303)
    lad = material_ladder()
    fq = [hz(r["midi"]) for r in lad]
    sbus, pbus = Bus(tl), Bus(tl)

    def hitf(f: float, t: float, vel: float, damp: float | None, label: str | None = None) -> None:
        life = None if damp is None else max(0.0, damp - t)
        sbus.add(strike(f, vel, rng, life), t, gain=0.22, pan=float(np.clip((np.log2(f / 82.4) - 2) / 3, -0.6, 0.6)))
        if label:
            reg.add(t, label, "v3.strikes")

    for i, s in enumerate(pa):
        hitf(fq[i], s.start, 1.0, H.start, f"L{i + 1}A {lad[i]['note']}")
    rates = [0.5, 0.25, 0.25, 0.125, 0.125, 0.0625, 0.0625]
    for i, s in enumerate(pb):
        hitf(fq[i], s.start, 0.95, H.start, f"L{i + 1}B {lad[i]['note']}")
        for j, t in enumerate(local_grid(s.start + rates[i], s.end, rates[i])):
            hitf(fq[i], t, float(np.clip(0.42 + 0.08 * rng.standard_normal() - 0.01 * j, 0.2, 0.6)), H.start,
                 f"L{i + 1}B restrike" if rates[i] >= 0.125 else None)
    # hero: everything damped at the cut; A4 (sus4, the gap) at the Cu contact; resolution chord when the line is gone
    hitf(fq[3], cu, 0.6, NM.start, f"hero {lad[3]['note']} (gap)")
    hitf(fq[0], cu, 0.5, NM.start)
    chord = [lad[0]["midi"], lad[1]["midi"], lad[2]["midi"], 68, lad[4]["midi"], lad[5]["midi"], lad[6]["midi"]]
    for j, m in enumerate(chord):
        hitf(float(hz(m)), lg, 0.95, NM.start, "hero resolve chord" if j == 0 else None)
    hitf(fq[0], NM.start, 0.8, None, f"name {lad[0]['note']} (1 mm)")
    hitf(fq[6], cc, 0.35, None, f"close contact {lad[6]['note']} (0.4 um)")
    # sparse pulse: tock on beats in pass A, 8ths in pass B, 8ths after the line is gone
    for a, b, step, g in [(pa[0].start, pb[0].start, spb, 0.12), (pb[0].start, H.start, spb / 2, 0.13),
                          (lg, NM.start, spb / 2, 0.10)]:
        for t in tl.beats_in(a, b, step, anchor=lg if a >= lg - 1e-6 else pa[0].beat_t):
            pbus.add(tock(rng), t, gain=g, pan=-0.1, until=NM.start)
    # drone E1 + E2
    damp = [H.start, NM.start]
    for d in damp:
        reg.add(d, "damp", "v3.strikes", "info")
    dr = osc(tl, np.full(tl.N, 28.0), (1.0, 0.5, 0.1), drive=1.2)
    da = periodic(tl, [(0.0, 0.30), (pa[0].start, 0.32), (pb[0].start, 0.42), (H.start - 0.01, 0.5),
                       (H.start + 0.06, 0.18), (lg - 0.02, 0.3), (lg + 0.3, 0.7), (NM.start - 0.005, 0.75),
                       (NM.start + 0.005, 0.0), (cc, 0.0), (cc + 0.4, 0.26), (tl.T - 1e-3, 0.30)])
    drone = dr * da * 0.22
    ir = make_ir(9, 2.8, 3.4)
    wet = reverb(tl, sbus.x.mean(0) * 0.8 + 0.1 * pbus.x.mean(0), ir, damp, fade=0.15) * 0.25
    return {"v3.strikes": sbus.x, "v3.pulse": pbus.x, "v3.drone": pan2(drone, 0.0), "v3.wet": wet}


