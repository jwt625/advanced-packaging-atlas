def write_mastered(path: Path, x: np.ndarray) -> tuple[np.ndarray, float]:
    """Master, write, then trim against ffmpeg's measurement until I is within 0.1 LU and TP <= -1 dBTP."""
    y, g = master(x)
    for _ in range(4):
        write(path, y)
        m = ffmpeg_loudness(path)
        d = TARGET_LUFS - m["I_LUFS"]
        if abs(d) <= 0.1 and m["TP_dBTP"] <= -1.0:
            break
        g += d
        y = limiter(y * 10 ** (d / 20), CEIL_DBTP)
    return y, g


def write(path: Path, x: np.ndarray) -> None:
    sf.write(str(path), x.T.astype(np.float32), SR, subtype="PCM_24" if path.stem.startswith("mix") else "FLOAT")


