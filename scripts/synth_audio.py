PEDAL_STOPS = [("Contrabass 32'", 0.25, [1.0], -12.0), ("Subbass 16'", 0.5, STOPPED, 0.0),
               ("Octave 8'", 1.0, PRINCIPAL, -5.0)]  # ratios re the pedal key E2 (8' pitch): E0, E1, E2


def _mark(mk: dict, key: str) -> float:
    if key == "start":
        return -1.0
    base, _, add = key.partition("+")
    return mk[base] + (float(add) if add else 0.0)


def harm_organ(tl: TL, harmony: list, mk: dict, seed: int, steps: list | None = None,
               voice_mod: dict | None = None) -> np.ndarray:
    """Manual organ on the chord tones (8' pitch one octave below the arp register): registration adds stops
    section by section (each rank fades in linearly in dB over its window), per-pipe detune of +/- 2 cents, a very soft
    chiff on every key-down, no tremulant; the overall swell follows ramp_db. Keys are released at the name-card cut.
    steps [(t, old midi, new midi)]: inside a held chord, that voice changes key at t (legato, 8 ms overlap, chiff
    on the new key only); the other keys stay held. voice_mod {"t0", "t1", "gain_db": {midi: dB}, "skip": {midi:
    [stop names]}}: per-key level and stops for chords starting in [t0, t1)."""
    rng = np.random.default_rng(seed)
    bus = Bus(tl)
    reg_db = []
    for _, _, _, lev, (k0, k1) in MANUAL_RANKS:
        t0, t1 = _mark(mk, k0), _mark(mk, k1)
        pts = [(0.0, lev)] if t0 < 0 else [(t0 - 1e-3, -60.0), (max(t1, t0 + 0.05), lev)]
        if t0 >= 0:
            pts = [(0.0, -60.0)] + pts
        pts += [(mk["NM"], lev), (mk["NM"] + 0.5, lev if t0 < 0 else -60.0), (tl.T - 1e-3, lev if t0 < 0 else -60.0)]
        reg_db.append(np.interp(tl.t, [p[0] for p in pts], [p[1] for p in pts]))
    for a, b, tones in harmony:
        if a >= mk["NM"] - 1e-3:
            continue  # the card: no new keys (the pedal carries it)
        end_card = abs(b - mk["NM"]) < 1e-3
        d = b - a + (0.0 if end_card else 0.06)
        n = ns(d)
        idx = (int(round(a * SR)) + np.arange(n)) % tl.N
        t = np.arange(n) / SR
        y = np.zeros(n)
        voices = []  # (midi, gate over the segment, chiff sample index)
        for m in tones:
            st = next(((tc, m2) for tc, m1, m2 in (steps or []) if m1 == m and a < tc < b), None)
            if st is None:
                voices.append((m, None, 0))
                continue
            ic, nx = int(round((st[0] - a) * SR)), ns(0.008)
            ramp_ = np.clip((np.arange(n) - ic + nx / 2) / nx, 0, 1)
            voices += [(m, 1 - ramp_, 0), (st[1], ramp_, max(0, ic - nx // 2))]
        vm = voice_mod if (voice_mod and voice_mod["t0"] - 1e-3 <= a < voice_mod["t1"] - 1e-3) else None
        for m, vg, ic0 in voices:
            key = float(hz(m - 12))
            vgain = 10 ** ((vm["gain_db"].get(m, 0.0) if vm else 0.0) / 20)
            for r, (stop, ratio, parts, _, _) in enumerate(MANUAL_RANKS):
                if vm and stop in vm["skip"].get(m, []):
                    continue
                g = 10 ** (reg_db[r][idx] / 20) * vgain
                if g.max() < 1e-3:
                    continue
                det = 2 ** (rng.uniform(-2, 2) / 1200)
                f1 = key * ratio * det
                pipe = np.zeros(n)
                for k, amp in enumerate(parts, start=1):
                    if f1 * k > 12000.0:
                        break
                    pipe += amp * np.sin(2 * np.pi * f1 * k * t + rng.random() * 2 * np.pi)
                nc = min(ns(0.025), n - ic0)  # chiff: a very soft breathy onset around the pipe's 2nd-3rd partial
                ch = signal.sosfilt(bp(min(2 * f1, 9000.0), min(3.5 * f1, 15000.0)), rng.standard_normal(nc))
                pipe[ic0: ic0 + nc] += 0.04 * ch * np.exp(-np.arange(nc) / (0.006 * SR))
                y += pipe * g * (1.0 if vg is None else vg)
        bus.add(fade_edges(y / np.sqrt(len(tones) * 3), 0.03, 0.12 if end_card else 0.06), a)
    return bus.x


def organ_pedal(tl: TL, mk: dict, seed: int, bump_db: float = 3.0, tau: float = 0.5,
                early: bool = False, contra_db: float | None = None) -> np.ndarray:
    """Pedal division on E (32' E0 kept modest, 16' Subbass E1, 8' Octave E2): one held key from the second before
    the hero, through the hero and across the name-card cut without re-attack, swelled +bump_db there with a 200 ms
    rise, then a slow decay (tau) into the quiet tail; partials under 600 Hz. early: the key goes down at the start
    of pass B instead and the pedal swells with the registration (-30 dB at pass B, -22 at the half-beat section,
    -13 at the quarter-beat section, 0 at the hero)."""
    rng = np.random.default_rng(seed)
    t0, t1 = (mk["b0"] if early else mk["H"] - 1.0), mk["cc"] + 0.3
    n = ns(t1 - t0)
    t = np.arange(n) / SR
    y = np.zeros(n)
    key = float(hz(40))  # E2 = 8' pitch of the pedal key
    for stop, ratio, parts, lev in PEDAL_STOPS:
        if contra_db is not None and stop.startswith("Contrabass"):
            lev = contra_db
        f1 = key * ratio * 2 ** (rng.uniform(-1.5, 1.5) / 1200)
        p0 = rng.random() * 2 * np.pi
        K = len(parts)
        for k, amp in enumerate(parts, start=1):
            if f1 * k > 600.0:
                break
            ph = p0 - np.pi * k * (k - 1) / K  # Schroeder phases: same spectrum, lower crest (less master limiting)
            y += 10 ** (lev / 20) * amp * np.sin(2 * np.pi * f1 * k * t + ph)
    t30 = 30.0 * tau / 8.686
    pk = mk["NM"] + 0.2
    xs = [t0, mk["H"], mk["NM"], pk, pk + t30, max(mk["CL"], pk + t30 + 0.05), mk["cc"], t1]
    ys = [-45.0, 0.0, 0.0, bump_db, bump_db - 30.0, bump_db - 31.0, bump_db - 34.0, -60.0]
    if early:
        xs = [t0, mk["c0"], mk["m0"]] + xs[1:]
        ys = [-30.0, -22.0, -13.0] + ys[1:]
    env_db = np.interp(t0 + t, xs, ys)
    bus = Bus(tl)
    bus.add(fade_edges(y * 10 ** (env_db / 20), 0.3 if early else 0.05, 0.05), t0)
    return bus.x


