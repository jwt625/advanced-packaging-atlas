def cmd_render(a: argparse.Namespace) -> int:
    tl = load_timeline()
    OUT.mkdir(parents=True, exist_ok=True)
    only = a.only or ["v1", "v2", "v3", "sfx"]
    a.only = only
    log(f"render {only}: {tl.T:.2f} s ({tl.N} samples) at {SR} Hz, bpm {tl.bpm}")
    reg_s = Reg()
    sfx_l = sfx(tl, reg_s)
    sfx_x = sum(sfx_l.values())
    report: dict = {"duration_s": tl.T, "samples": tl.N, "ladder": material_ladder(), "files": {}}
    tag = "" if any(v in ("v1", "v2", "v3", "sfx") for v in only) else (
        "_alts" if set(only) <= {"v2_alt_A", "v2_alt_B", "v2_alt_C"} else "_" + "_".join(v.removeprefix("v2_") for v in only))
    vpath = outp(f"verify{tag}.json")  # rewritten each run: covers what this run rendered
    report["events"] = {}
    report["cue_levels"] = {}
    report["cue_targets_db"] = CUE_TARGET_DB
    if not a.no_verify:
        report["events"]["sfx"] = verify_events(tl, sfx_l, reg_s)
    if "sfx" in only:
        write(outp("sfx.wav"), sfx_x)
        mx, g = write_mastered(outp("mix_sfx.wav"), sfx_x)
        log(f"sfx: stem + mix_sfx (gain {g:+.1f} dB)")
        if not a.no_verify:
            report["files"][outp("mix_sfx.wav").name] = {**ffmpeg_loudness(outp("mix_sfx.wav")), "seam": seam_check(mx),
                                                    "name_cut": name_cut_check(tl, mx)}
            spectrogram(tl, mx, outp("spec_sfx.png"))
    for v in [x for x in only if x in VERSIONS]:
        fn, name = VERSIONS[v]
        reg = Reg()
        layers = fn(tl, reg)
        music = sum(layers.values())
        gm = 10 ** ((MUSIC_LUFS - lufs(music)) / 20)
        music = music * gm
        layers = {k: x * gm for k, x in layers.items()}
        layers[f"{v}.music"] = music
        write(outp(f"music_{v}.wav"), music)
        # SFX cue levels are set against the groove; an alternative's harmonic layer does not raise them
        reg_v = Reg()
        sfx_lv = sfx(tl, reg_v, organ=True) if v in ORGAN_SFX else sfx_l
        sfx_v, cg = level_cues(tl, music - layers.get(f"{v}.harm", 0.0), sfx_lv)
        write(outp(f"sfx_{v}.wav"), sfx_v)
        mx, g = write_mastered(outp(f"mix_{v}.wav"), music + sfx_v)
        report.setdefault("cue_gains_db", {})[v] = {k: round(x, 1) for k, x in cg.items()}
        log(f"{v} {name}: music gain {20 * np.log10(gm):+.1f} dB, mix gain {g:+.1f} dB; layers "
            + ", ".join(f"{k} {lufs(x):.1f}" for k, x in layers.items() if np.any(x)))
        if not a.no_verify:
            report["events"][v] = verify_events(tl, layers, reg)
            if v in ORGAN_SFX:
                report["events"][f"sfx_{v}"] = verify_events(tl, sfx_lv, reg_v)
            report["cue_levels"][v] = cue_levels(tl, music - layers.get(f"{v}.harm", 0.0), {k: x * 10 ** (cg.get(k, 0.0) / 20)
                                                              for k, x in sfx_lv.items()})
            report["files"][outp(f"mix_{v}.wav").name] = {**ffmpeg_loudness(outp(f"mix_{v}.wav")), "seam": seam_check(mx),
                                                       "name_cut": name_cut_check(tl, mx),
                                                       "hf_pulse": hf_pulse_start(tl, mx),
                                                       "card_margin": card_margin(tl, mx),
                                                       "card_bloom": {"harm_layer": bloom_env(tl, layers[f"{v}.harm"]),
                                                                      "mix": bloom_env(tl, mx)}
                                                       if f"{v}.harm" in layers else None,
                                                       "cut": cut_check(tl, mx),
                                                       "pedal_max_rise_db_per_50ms_near_cut":
                                                       max_rise(layers[f"{v}.pedal"], tl["name"].start)
                                                       if f"{v}.pedal" in layers else None,
                                                       "section_rates": section_rates(tl, layers[f"{v}.kick"], mx)
                                                       if f"{v}.kick" in layers else None}
            spectrogram(tl, mx, outp(f"spec_{v}.png"))
    if not a.no_verify:
        for key, evs in report["events"].items():
            bad = [e for e in evs if "err_ms" in e and (e["err_ms"] is None or abs(e["err_ms"]) > 1000 * TOL)]
            log(f"events {key}: {len(evs)} checked, {len(bad)} outside +/- {1000 * TOL:.0f} ms")
            for e in bad:
                log(f"  OUTSIDE {e['label']} @ {e['t']:.3f}: {e.get('err_ms')}")
        for f, d in report["files"].items():
            log(f"{f}: I {d['I_LUFS']} LUFS, TP {d['TP_dBTP']} dBTP, LRA {d['LRA_LU']} LU, "
                f"click_free {d['seam']['click_free']}")
            for k in ("cut", "card_bloom", "pedal_max_rise_db_per_50ms_near_cut"):
                if k in d:
                    log(f"  {k}: {d[k]}")
        vpath.write_text(json.dumps(report, indent=1, ensure_ascii=False), encoding="utf-8")
        log(f"wrote {vpath.relative_to(ROOT)}")
    return 0


def tonal_frames(x: np.ndarray, hop_s: float = 0.05) -> dict:
    """Per-frame tonal metrics: number of strong spectral peaks (60 Hz - 8 kHz, >= 12 dB over the local median
    spectrum and within 50 dB of the frame maximum), their power-weighted centroid and bandwidth (std), and the
    K-weighted 400 ms loudness (LUFS-like)."""
    mono = x.mean(0) if x.ndim == 2 else x
    nfft, hop = 8192, int(hop_s * SR)
    f, t, Z = signal.stft(mono, SR, nperseg=nfft, noverlap=nfft - hop, boundary=None, padded=False)
    P = 20 * np.log10(np.abs(Z) + 1e-9)
    band = (f >= 60) & (f <= 8000)
    fb, Pb = f[band], P[band]
    med = ndimage.median_filter(Pb, size=(int(300 / (f[1] - f[0])) | 1, 1), mode="nearest")
    cnt, cen, bw = [], [], []
    for j in range(Pb.shape[1]):
        col = Pb[:, j]
        pk, _ = signal.find_peaks(col, distance=3)
        pk = pk[(col[pk] - med[pk, j] >= 12) & (col[pk] >= col.max() - 50) & (col[pk] > -100)]
        cnt.append(len(pk))
        if len(pk):
            w = 10 ** (col[pk] / 10)
            c = float((w * fb[pk]).sum() / w.sum())
            cen.append(c)
            bw.append(float(np.sqrt((w * (fb[pk] - c) ** 2).sum() / w.sum())))
        else:
            cen.append(np.nan)
            bw.append(np.nan)
    y = signal.lfilter(*K2, signal.lfilter(*K1, x if x.ndim == 2 else x[None], axis=1), axis=1)
    e = ndimage.uniform_filter1d((y ** 2).sum(0), ns(0.4))
    lk = -0.691 + 10 * np.log10(np.maximum(e[np.clip((t * SR).astype(int), 0, e.size - 1)], 1e-12))
    return {"t": t, "count": np.array(cnt, float), "centroid": np.array(cen), "bandwidth": np.array(bw), "lufs": lk}


def band_db(x: np.ndarray, a: float, b: float) -> dict:
    mono = x.mean(0) if x.ndim == 2 else x
    seg = mono[int(a * SR): int(b * SR)]
    sp = np.abs(np.fft.rfft(seg * np.hanning(seg.size))) ** 2
    fr = np.fft.rfftfreq(seg.size, 1 / SR)
    out = {}
    for lo, hi in [(20, 120), (120, 500), (500, 2000), (2000, 8000), (8000, 16000)]:
        out[f"{lo}-{hi}"] = float(10 * np.log10(sp[(fr >= lo) & (fr < hi)].sum() / seg.size + 1e-20))
    return out


def cmd_compare(a: argparse.Namespace) -> int:
    """Harmonic-build metrics of a reference (its card at --ref-card) vs our mixes (card = the name-card cut), with
    the time axis aligned on each card; spectrograms and curves side by side."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    tl = load_timeline()
    card = tl["name"].start
    items = [("Opus reference", Path(a.ref), a.ref_card)]
    items += [(m.removeprefix("mix_").removesuffix(".wav"), OUT / m, card) for m in a.mixes if (OUT / m).exists()]
    res, curves = {}, {}
    for name, path, tc in items:
        x, sr = sf.read(str(path), always_2d=True)
        x = x.T
        if sr != SR:
            x = signal.resample_poly(x, SR, sr, axis=1)
        m = tonal_frames(x)
        curves[name] = (m, tc, x)
        dur = x.shape[1] / SR
        sm = lambda v: ndimage.uniform_filter1d(np.nan_to_num(v, nan=0.0), 10)  # 0.5 s
        cs, lks, cen = sm(m["count"]), ndimage.uniform_filter1d(m["lufs"], 10), m["centroid"]
        secs = {}
        for lab, f0, f1 in [("0-25%", 0, 0.25), ("25-50%", 0.25, 0.5), ("50-75%", 0.5, 0.75), ("75-100%", 0.75, 1.0)]:
            w0, w1 = f0 * tc, f1 * tc
            sel = (m["t"] >= w0) & (m["t"] < w1)
            secs[lab] = {"partials": round(float(np.mean(m["count"][sel])), 1),
                         "tonal_centroid_hz": round(float(np.nanmean(cen[sel])), 0),
                         "tonal_bandwidth_hz": round(float(np.nanmean(m["bandwidth"][sel])), 0),
                         "lufs_400ms": round(float(np.mean(m["lufs"][sel])), 1),
                         "bands_db": {k: round(v, 1) for k, v in band_db(x, w0, w1).items()}}
        sel = (m["t"] >= tc) & (m["t"] < min(tc + 1.2, dur))
        secs["card+1.2s"] = {"partials": round(float(np.mean(m["count"][sel])), 1),
                             "tonal_centroid_hz": round(float(np.nanmean(cen[sel])), 0),
                             "tonal_bandwidth_hz": round(float(np.nanmean(m["bandwidth"][sel])), 0),
                             "lufs_400ms": round(float(np.mean(m["lufs"][sel])), 1),
                             "bands_db": {k: round(v, 1) for k, v in band_db(x, tc, min(tc + 1.2, dur)).items()}}
        pre = m["t"] < tc + 1.2
        res[name] = {"file": path.name, "card_s": tc, "sections": secs,
                     "peak_partials_rel_card_s": round(float(m["t"][pre][np.argmax(cs[pre])] - tc), 2),
                     "peak_lufs_rel_card_s": round(float(m["t"][pre][np.argmax(lks[pre])] - tc), 2),
                     "partials_ramp_first_to_last_quarter": round(secs["75-100%"]["partials"] - secs["0-25%"]["partials"], 1),
                     "lufs_ramp_first_to_last_quarter": round(secs["75-100%"]["lufs_400ms"] - secs["0-25%"]["lufs_400ms"], 1)}
        log(f"{name}: partials/frame by quarter "
            + " / ".join(f"{secs[k]['partials']}" for k in ("0-25%", "25-50%", "50-75%", "75-100%"))
            + f", card {secs['card+1.2s']['partials']}; centroid "
            + " / ".join(f"{secs[k]['tonal_centroid_hz']:.0f}" for k in ("0-25%", "25-50%", "50-75%", "75-100%"))
            + f" Hz; LUFS(400ms) " + " / ".join(f"{secs[k]['lufs_400ms']}" for k in ("0-25%", "25-50%", "50-75%", "75-100%"))
            + f", card {secs['card+1.2s']['lufs_400ms']}; peak partials {res[name]['peak_partials_rel_card_s']:+.2f} s "
            f"and peak loudness {res[name]['peak_lufs_rel_card_s']:+.2f} s re card")
    (OUT / "compare_metrics.json").write_text(json.dumps(res, indent=1), encoding="utf-8")
    # spectrograms, aligned on the card (x = t - card)
    n = len(items)
    fig, axs = plt.subplots(n, 1, figsize=(16, 2.6 * n), sharex=True, facecolor="#0b0d10")
    for ax, (name, path, tc) in zip(np.atleast_1d(axs), items):
        x = curves[name][2]
        f, t, Z = signal.stft(x.mean(0), SR, nperseg=4096, noverlap=4096 - 480)
        S = 20 * np.log10(np.abs(Z) + 1e-9)
        S -= S.max()
        mm = f >= 20
        ax.set_facecolor("#0b0d10")
        ax.pcolormesh(t - tc, f[mm], S[mm], vmin=-90, vmax=0, cmap="magma", shading="auto", rasterized=True)
        ax.set_yscale("log")
        ax.set_ylim(40, 16000)
        ax.axvline(0, color="#7fb3d5", lw=0.8)
        ax.text(0.005, 0.92, name, transform=ax.transAxes, color="#cfe3f0", fontsize=8, va="top")
        ax.tick_params(colors="#9aa4ad", labelsize=7)
        ax.set_ylabel("Hz", color="#9aa4ad", fontsize=8)
    np.atleast_1d(axs)[-1].set_xlabel("s relative to the name card", color="#9aa4ad")
    fig.tight_layout()
    fig.savefig(OUT / "compare_spec.png", dpi=100, facecolor=fig.get_facecolor())
    plt.close(fig)
    fig, axs = plt.subplots(3, 1, figsize=(14, 8), sharex=True, facecolor="#0b0d10")
    cols = ["#e8e3d8", "#7fb3d5", "#d9a066", "#9ccf8f", "#c792ea"]
    for (name, (m, tc, _)), c in zip(curves.items(), cols):
        sm = lambda v: ndimage.uniform_filter1d(np.nan_to_num(v, nan=np.nanmean(v)), 10)
        for ax, key, lab in zip(axs, ("count", "centroid", "lufs"),
                                ("strong partials / frame", "tonal centroid (Hz)", "loudness 400 ms (LUFS)")):
            ax.plot(m["t"] - tc, sm(m[key]), color=c, lw=1.2 if name.startswith("Opus") else 0.9, label=name)
            ax.set_ylabel(lab, color="#9aa4ad", fontsize=8)
    for ax in axs:
        ax.set_facecolor("#0b0d10")
        ax.axvline(0, color="#7fb3d5", lw=0.6)
        ax.tick_params(colors="#9aa4ad", labelsize=7)
    axs[0].legend(fontsize=7, facecolor="#0b0d10", labelcolor="#cfe3f0", edgecolor="#3a4048")
    axs[-1].set_xlabel("s relative to the name card", color="#9aa4ad")
    fig.tight_layout()
    fig.savefig(OUT / "compare_curves.png", dpi=100, facecolor=fig.get_facecolor())
    plt.close(fig)
    log("wrote cache/video/audio/compare_metrics.json, compare_spec.png, compare_curves.png")
    return 0


def probe_duration(path: Path) -> float:
    r = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "stream=nb_frames,duration",
                        "-of", "json", str(path)], capture_output=True, text=True, check=True)
    st = json.loads(r.stdout)["streams"][0]
    return float(st["duration"])


def cmd_mux(a: argparse.Namespace) -> int:
    tl = load_timeline()
    edit = json.loads(Path(CFG["edit"]).read_text(encoding="utf-8"))
    video = MEDIA / edit["output"]
    vd = probe_duration(video)
    if abs(vd - tl.T) > 0.5 / tl.fps:
        log(f"ERROR draft video {vd:.3f} s != edit.json {tl.T:.3f} s; not muxing")
        return 1
    EVAL.mkdir(parents=True, exist_ok=True)
    targets = {"v1": ("mix_v1.wav", "v1_vowel.mp4"), "v2": ("mix_v2.wav", "v2_synthetic.mp4"),
               "v3": ("mix_v3.wav", "v3_material.mp4"), "sfx": ("mix_sfx.wav", "sfx_only.mp4"),
               "v2_alt_A": ("mix_v2_alt_A.wav", "v2_alt_A.mp4"), "v2_alt_B": ("mix_v2_alt_B.wav", "v2_alt_B.mp4"),
               "v2_alt_C": ("mix_v2_alt_C.wav", "v2_alt_C.mp4"),
               "v2_alt_A_organ": ("mix_v2_alt_A_organ.wav", "v2_alt_A_organ.mp4")}
    only = getattr(a, "only", None) or ["v1", "v2", "v3", "sfx"]
    for wav, mp4 in [targets[k] for k in only if k in targets]:
        src = outp(wav)
        mp4 = outp(mp4, EVAL).name
        if not src.exists():
            log(f"skip {mp4}: no {src.name}")
            continue
        ad = sf.info(str(src)).duration
        if abs(ad - tl.T) > 0.5 / tl.fps:
            log(f"ERROR {wav} {ad:.3f} s != {tl.T:.3f} s; not muxing")
            return 1
        subprocess.run(["ffmpeg", "-v", "error", "-y", "-i", str(video), "-i", str(src), "-map", "0:v:0", "-map", "1:a:0",
                        "-c:v", "copy", "-c:a", "aac", "-b:a", "128k", "-ar", "48000", "-ac", "2", "-t", f"{tl.T:.3f}",
                        "-movflags", "+faststart", str(EVAL / mp4)], check=True)
        log(f"muxed {(EVAL / mp4).relative_to(ROOT)} (video {vd:.3f} s, audio {ad:.3f} s)")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    names = ["v1", "v2", "v3", "sfx", "v2_alt_A", "v2_alt_B", "v2_alt_C", "v2_alt_A_organ"]
    ps = [sub.add_parser("events")]
    mx = sub.add_parser("mux")
    mx.add_argument("--only", nargs="*", choices=names)
    ps.append(mx)
    for name in ("render", "all"):
        r = sub.add_parser(name)
        r.add_argument("--only", nargs="*", choices=names)
        r.add_argument("--no-verify", action="store_true")
        ps.append(r)
    cp = sub.add_parser("compare")
    cp.add_argument("--ref", required=True, help="reference audio file (analysed only)")
    cp.add_argument("--ref-card", type=float, default=16.0, help="time of the reference's name card (s)")
    cp.add_argument("--mixes", nargs="*", default=["mix_v2.wav", "mix_v2_alt_A.wav", "mix_v2_alt_B.wav",
                                                    "mix_v2_alt_C.wav"])
    ps.append(cp)
    for x in ps:
        x.add_argument("--edit", default=str(MEDIA / "edit.json"))
    a = ap.parse_args()
    ed = Path(a.edit).resolve()
    CFG["edit"] = ed
    CFG["suffix"] = "" if ed.stem == "edit" else "_" + ed.stem.removeprefix("edit_")
    log(f"edit file {ed.relative_to(ROOT) if ed.is_relative_to(ROOT) else ed}; output suffix {CFG['suffix']!r}")
    if a.cmd == "events":
        return cmd_events(a)
    if a.cmd == "render":
        return cmd_render(a)
    if a.cmd == "mux":
        return cmd_mux(a)
    if a.cmd == "compare":
        return cmd_compare(a)
    if a.cmd == "all":
        return cmd_render(a) or cmd_mux(a)
    return 1


if __name__ == "__main__":
    raise SystemExit(main())
