@dataclass
class Shot:
    id: str
    scene: str
    frames: int
    beats: float
    start: float
    dur: float
    params: dict
    beat_t: float = 0.0

    @property
    def speed(self) -> float:
        """Scene time = shot time * speed (edit.json param `speed`, default 1)."""
        return float(self.params.get("speed", 1.0))  # beat-grid time of the cut (grid0 + cumulative beats * spb), within half a frame of start

    @property
    def end(self) -> float:
        return self.start + self.dur


@dataclass
class TL:
    fps: int
    bpm: float
    spb: float
    shots: list[Shot]
    T: float
    N: int
    grid0: float
    t: np.ndarray = field(repr=False)

    def __getitem__(self, sid: str) -> Shot:
        for s in self.shots:
            if s.id == sid:
                return s
        raise KeyError(f"edit.json has no shot {sid!r}")

    def es(self, key: str) -> Shot:
        """The shot that shows the scene an event table belongs to (EVENT_SCENES), else the shot with that id."""
        scene = EVENT_SCENES.get(key)
        for s in self.shots:
            if scene and s.scene == scene:
                return s
        return self[key]

    def ev(self, sid: str, key: str) -> float:
        """Absolute time of a scalar scene event (scene time / speed after the shot start)."""
        s = self.es(sid)
        return s.start + float(EVENTS[sid][key]) / s.speed  # type: ignore[arg-type]

    def evs(self, sid: str, key: str) -> list[float]:
        """Absolute times of a list event, dropping the ones past the shot's cut."""
        s = self.es(sid)
        out = []
        for x in EVENTS[sid][key]:  # type: ignore[union-attr]
            if x / s.speed < s.dur:
                out.append(s.start + float(x) / s.speed)
            else:
                log(f"WARNING event {sid}.{key} at {x} s is past the cut ({s.dur:.2f} s); dropped")
        return out

    def pa(self) -> list[Shot]:
        return [self[f"l{k}a"] for k in range(1, 8)]

    def pb(self) -> list[Shot]:
        return [self[f"l{k}b"] for k in range(1, 8)]

    def section(self, letter: str) -> list[Shot]:
        """Content shots of pass A / B / C / M in cut order: ids l..a / l..b / l..c (e.g. l1a, l1fa); an id without
        that form falls back on its length (>= 2 beats A, 1 beat B, 0.5 beat C, <= 0.25 beat M)."""
        out = []
        for s in self.shots:
            if s.id in ("open", "hero", "name", "close"):
                continue
            m = re.match(r"^l\w*?([abc])$", s.id)
            sec = m.group(1) if m else ("a" if s.beats >= 2 else "b" if s.beats >= 1 else "c" if s.beats >= 0.5
                                        else "m")
            if sec == letter:
                out.append(s)
        return out

    def beats_in(self, t0: float, t1: float, step: float, anchor: float | None = None,
                 guard: float = 0.03) -> list[float]:
        """Grid times (anchor + k step, default anchor grid0) in [t0 - 15 ms, t1 - guard)."""
        g = self.grid0 if anchor is None else anchor
        k = int(np.ceil((t0 - g - 0.015) / step))
        out = []
        while g + k * step < t1 - guard:
            out.append(g + k * step)
            k += 1
        return out


def scene_events(tl: TL) -> None:
    """Open / close events (scene time) from the s00_horizon.html formulas for the current shot lengths."""
    d = (tl["open"].frames - 1) / tl.fps
    EVENTS["open"] = {"split": round(d - min(0.72, 0.6 * d), 4), "split_done": round(d, 4)}
    d = (tl["close"].frames - 1) / tl.fps
    tw = d - 2 / tl.fps
    tc = max(0.0, tw - min(0.42, 0.4 * d))
    EVENTS["close"] = {"contact": round(tc, 4), "front_end": round(tw, 4)}


def close_front_x(tl: TL, t_rel: np.ndarray) -> np.ndarray:
    """Glow-front x (px) in the close at seconds-from-shot-start t_rel (s00_horizon.html mode=close)."""
    tc, tw = float(EVENTS["close"]["contact"]), float(EVENTS["close"]["front_end"])  # type: ignore[arg-type]
    u = np.clip((t_rel * tl["close"].speed - tc) / max(tw - tc, 1e-6), 0, 1)
    return -420.0 + 2760.0 * u * u * (3 - 2 * u)


def load_timeline() -> TL:
    edit = json.loads(Path(CFG["edit"]).read_text(encoding="utf-8"))
    fps = int(edit["fps"])
    bpm = float(edit.get("bpm", 120.0))
    spb = 60.0 / bpm
    shots, f = [], 0
    for s in edit["shots"]:
        shots.append(Shot(s["id"], s["scene"], int(s["frames"]), float(s.get("beats", 0.0)), f / fps,
                          s["frames"] / fps, s.get("params", {})))
        f += int(s["frames"])
    T = f / fps
    N = int(round(T * SR))
    first = shots[0]
    grid0 = max(0.0, round(first.dur - first.beats * spb, 3)) if first.beats else 0.0
    tl = TL(fps, bpm, spb, shots, T, N, grid0, np.arange(N) / SR)
    acc = grid0
    for s in shots:
        s.beat_t = acc
        acc += s.beats * spb
    scene_events(tl)
    for k in range(1, 8):  # cross-check the pitch ladder against the overlay text
        txt = tl[f"l{k}b"].params.get("text", "")
        m = re.match(r"([\d.]+)\s*(mm|µm|um)", txt)
        if m:
            um = float(m.group(1)) * (1000.0 if m.group(2) == "mm" else 1.0)
            if abs(um - LEVEL_PITCH_UM[k]) > 1e-9:
                log(f"WARNING l{k}b text {txt!r} != ladder {LEVEL_PITCH_UM[k]} um")
    return tl


