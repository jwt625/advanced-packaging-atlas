CHORDS = {  # bass root (E2..D3 region), pad / arp tones
    "Em": (40, [64, 67, 71]),
    "C": (48, [60, 64, 67]),
    "G": (43, [62, 67, 71]),
    "D": (38, [62, 66, 69]),
}


def v2(tl: TL, reg: Reg, opts: dict | None = None) -> dict[str, np.ndarray]:
    """opts (alternatives only; None = the plan-of-record V2): shift [(t0, t1, semitones)] transposes the pitched
    layers in [t0, t1); card_chord / card_sub (midi) replace the name-card Em pad / E1 sub. Writes the harmony back
    into opts["_harmony"] for layers built on top.
    Sections: open = 2-beat pickup; 4-beat bars from the first pass-A cut (close + open form one bar across the
    loop); pass A kick per beat, pass B kick per beat (= per cut), pass C kick per half beat (= per cut, double time);
    hero = break then drop; name card = resolution (Em pad + E1 sub, no impact)."""
    SA, SB, SC, SM = tl.section("a"), tl.section("b"), tl.section("c"), tl.section("m")
    OP, H, NM = tl["open"], tl["hero"], tl["name"]
    cc, osp = tl.ev("close", "contact"), tl.ev("open", "split")
    spb = tl.spb
    bar = 4 * spb
    A = SA[0].beat_t  # bar downbeat on the first content cut
    rng = np.random.default_rng(202)
    STOPF = 0.025  # release of the groove at the name-card cut
    a0, b0 = SA[0].start, SB[0].start
    m0 = SM[0].start if SM else H.start
    c0 = SC[0].start if SC else m0

    def q(t: float, step: float) -> float:
        return A + round((t - A) / step) * step

    # hero moments quantized to the grid; the drop on the beat nearest the end of the Cu-Cu line dissolve, kept at
    # least one beat before the name card
    lg = min(q(tl.ev("hero", "line_gone"), spb), q(NM.start, spb) - spb)
    cu = min(q(tl.ev("hero", "cu_contact"), spb / 4), lg - spb / 4)
    an = min(q(tl.ev("hero", "anneal"), spb / 4), cu)
    # the hero is two 2-beat intervals with the same high background pattern (owner, 2026-10-22; supersedes the
    # earlier "no highs in the last beat"): dark 16th arps on both beats, gated 4.5-5.5 kHz noise on the second beat;
    # it runs to the name card and ends with a 60 ms release before the cut
    hi_end = NM.start
    HIREL = 0.06
    log(f"v2 sections: A {len(SA)} shots from {a0:.2f}, B {len(SB)} from {b0:.2f}, C {len(SC)} from {c0:.2f}, "
        f"M {len(SM)} from {m0:.2f}, hero "
        f"{H.start:.2f}, name {NM.start:.2f}; hero grid: line_gone {tl.ev('hero', 'line_gone'):.3f} -> {lg:.3f}, "
        f"cu_contact {tl.ev('hero', 'cu_contact'):.3f} -> {cu:.3f}, anneal {tl.ev('hero', 'anneal'):.3f} -> {an:.3f}")
    o = opts if opts is not None else {}
    card_chord = o.get("card_chord", [52, 59, 64, 67])
    card_sub = o.get("card_sub", 28)

    def shift(t: float) -> int:
        for t0, t1, st in o.get("shift", []):
            if t0 - 1e-6 <= t < t1 - 1e-6:
                return st
        return 0

    def root_at(t: float) -> int:
        return CHORDS[chord_at(t)][0] + shift(t)

    def tones_at(t: float) -> list[int]:
        return [x + shift(t) for x in CHORDS[chord_at(t)][1]]

    prog = ["Em", "C", "G", "D"]

    def chord_at(t: float) -> str:
        if t < A - 1e-6:
            return "Em"
        if t < H.start - 1e-6:
            return prog[int((t - A + 1e-6) // bar) % 4]
        if t < cu - 1e-6:
            return "C"
        if t < NM.start - 1e-6:
            return "D"
        return "Em"

    def grid(a: float, b: float, step: float) -> list[float]:
        return tl.beats_in(a, b, step, anchor=A)

    def bi(t: float, step: float) -> int:
        return int(round((t - A) / step))

    segs: list[tuple[float, float, str]] = []
    t0 = A
    while t0 < H.start - 1e-6:
        segs.append((t0, min(t0 + bar, H.start), chord_at(t0)))
        t0 += bar
    segs += [(H.start, cu, "C"), (cu, NM.start, "D")]
    drop = b0 - spb  # lows out for the last beat of pass A
    kick_b, drums, bass, arps, pads, fx = Bus(tl), Bus(tl), Bus(tl), Bus(tl), Bus(tl), Bus(tl)
    # opening (pickup): 47 Hz sub from the close contact, held, chirp 47 -> 188 Hz while the halves split, into the
    # first downbeat; crackle rising with the split
    pre = tl.T - cc
    rise = a0 - osp
    n = ns(pre + a0 + 0.08)
    tt = np.arange(n) / SR - pre
    u = np.clip((tt - osp) / rise, 0, 1)
    f = 47.0 * 4.0 ** (u ** 1.6)
    env = (np.clip((tt + pre) / 0.25, 0, 1) ** 2 * np.where(tt < a0, 1.0, np.clip(1 - (tt - a0) / 0.08, 0, 1))
           * (0.45 + 0.55 * u))
    fx.add(np.sin(2 * np.pi * np.cumsum(f) / SR) * env, cc, gain=0.5)
    t = osp
    while t < a0:
        t += rng.exponential(1.0 / (6.0 + 18.0 * (t - osp) / rise))
        nc = ns(rng.uniform(0.0005, 0.0015))
        c = signal.sosfilt(bp(3000.0, 7000.0), rng.standard_normal(nc + 64))[64:] * np.hanning(nc)
        fx.add(c, t, gain=0.15 * rng.uniform(0.4, 1.0), pan=rng.uniform(-0.8, 0.8))
    # kick: per beat in A and B, per half beat in C (every cut); groove back on the drop in the hero
    def kgain(t: float, step: float) -> float:
        if step == spb:
            return 0.55
        if step == spb / 2:
            return 0.55 if bi(t, spb / 2) % 2 == 0 else 0.4
        on8 = abs((t - A) / (spb / 2) - bi(t, spb / 2)) < 1e-6  # M: heavy on 8ths, light on the off-16ths, crescendo
        return (0.5 if on8 else 0.28) * (0.85 + 0.15 * (t - m0) / max(H.start - m0, 1e-6))

    # hero: 2-beat intervals of one style (owner, 2026-10-22): a clean kick on the first beat of each interval
    hero_iv = [(float(t), min(float(t) + 2 * spb, NM.start)) for t in np.arange(H.start, NM.start - 1e-6, 2 * spb)]
    for a, _ in hero_iv:
        kick_b.add(kick(rng), a, gain=0.6, until=NM.start, fade=STOPF)
    for a, b, step in [(a0, drop, spb), (b0, c0, spb), (c0, m0, spb / 2), (m0, H.start, spb / 4)]:
        for t in grid(a, b, step):
            kick_b.add(kick(rng, 0.18 if step == spb / 4 else 0.3), t,
                       gain=kgain(t, step), until=NM.start, fade=STOPF)
    for s in SA + SB + SC + SM:
        reg.add(s.start, f"kick on cut {s.id}", "v2.kick")
    reg.add(H.start, "hero downbeat", "v2.kick")
    for a, _ in hero_iv[1:]:
        reg.add(a, "hero 2-beat interval downbeat", "v2.kick")
    for s in (SB[0], *(SC[:1]), *(SM[:1])):
        reg.add(s.start, f"section downbeat {s.id}", "v2.kick")
    # clap on 2 and 4, hats from the first content cut: 8ths in A, 16ths in B, 32nds in C and the drop
    for a, b in [(a0, drop), (b0, H.start)]:
        for t in grid(a, b, spb):
            if bi(t, spb) % 2 == 1:
                drums.add(clap(rng), t, gain=0.22, pan=0.05, until=hi_end, fade=HIREL)
    for t in grid(a0, drop, spb / 2):
        drums.add(hat(rng, 0.025), t, gain=0.10 if bi(t, spb / 2) % 2 else 0.05, pan=0.25)
    reg.add(a0, "hat pulse starts with the first content cut", "v2.drums")
    # (M keeps the pass-C hats: only the low / background pulse doubles there; owner, 2026-10-22)
    for a, b, step in [(b0, c0, spb / 4), (c0, H.start, spb / 8)]:
        for t in grid(a, b, step):
            acc = abs((t - A) / (spb / 2) - bi(t, spb / 2)) < 1e-6  # on a half beat
            drums.add(hat(rng, 0.018 if step >= spb / 4 else 0.012), t, gain=0.10 if acc else 0.06, pan=0.25,
                      until=hi_end, fade=HIREL)
    # bass: 8ths, one-bar pattern; one long note through the hero break
    pat = [0, 0, 12, 0, 0, 12, 7, 0]
    for a, b, fc in [(a0, drop, 700.0), (b0, c0, 1100.0), (c0, m0, 1400.0)]:
        for t in grid(a, b, spb / 2):
            root = root_at(t)
            bass.add(pluck(root + pat[bi(t, spb / 2) % 8], spb / 2, fc, 0.11, "saw",
                           detune=7.0, sub=0.5), t,
                     gain=0.30, until=NM.start, fade=STOPF)
    for t in grid(m0, H.start, spb / 4):  # M: 16th bass, filter opening into the hero
        root = root_at(t)
        fc = 1400.0 + 1000.0 * (t - m0) / max(H.start - m0, 1e-6)
        bass.add(pluck(root + (12 if bi(t, spb / 4) % 2 else 0), spb / 4, fc, 0.07, "saw", detune=7.0, sub=0.5), t,
                 gain=0.28, until=H.start, fade=STOPF)
    hb = [(H.start, cu, "C"), (cu, hero_iv[1][0] if len(hero_iv) > 1 else NM.start, "D")]
    hb += [(a, b, "D") for a, b in hero_iv[1:]]  # the long bass note re-attacked on each interval's first beat
    for a, b, c in hb:
        if b > a + 1e-6:
            bass.add(pluck(CHORDS[c][0] + shift(a), b - a + 0.05, 500.0, 2.0, "saw", detune=7.0, sub=0.7), a,
                     gain=0.30, until=b,
                     fade=STOPF if b >= NM.start - 1e-6 else 0.006)
    reg.add(H.start, "hero cut: break bass note", "v2.bass")

    # arps: pulse 25 %, 8ths in A, 16ths in B, 16ths with an accent on every half-beat cut in C; dark in the break
    def arp_run(a: float, b: float, step: float, fc0: float, fc1: float, tau: float, g: float,
                accent: float = 1.0, cstep: float = spb / 2, until: float | None = None) -> None:
        for t in grid(a, b, step):
            j = bi(t, step)
            tones = tones_at(t)
            m = [tones[0], tones[1], tones[2], tones[0] + 12][j % 4] + (12 if (j // 4) % 2 else 0)
            fc = fc0 + (fc1 - fc0) * (t - a) / max(b - a, 1e-6)
            on_cut = abs((t - A) / cstep - bi(t, cstep)) < 1e-6
            arps.add(pluck(m, step * 1.6, fc * (1.5 if on_cut and accent > 1 else 1.0), tau, "pulse", duty=0.25), t,
                     gain=g * (accent if on_cut else 1.0), pan=0.35 if j % 2 else -0.35,
                     until=hi_end if until is None else until, fade=HIREL if until is None else STOPF)

    arp_run(a0, b0, spb / 2, 1400.0, 1800.0, 0.07, 0.10)
    reg.add(a0, "arp pulse starts with the first content cut", "v2.arps")
    arp_run(b0, c0, spb / 4, 1500.0, 4000.0, 0.05, 0.09)
    arp_run(c0, m0, spb / 4, 4000.0, 6000.0, 0.045, 0.085, accent=1.5)
    arp_run(m0, H.start, spb / 4, 6000.0, 6000.0, 0.045, 0.085, accent=1.5)  # M: pass-C arps, cutoff held
    for a, b in hero_iv:  # the same dark 16th arps in every 2-beat interval of the hero
        arp_run(a, b, spb / 4, 700.0, 950.0, 0.05, 0.08)
    # pads per bar (hero: per harmony); the groove stops on the name card; resolution: Em pad + E1 sub swell through
    # the name card and the close, overlapping the loop seam into the open
    for a, b, c in segs:
        g = 0.10 if a < b0 else (0.13 if a < H.start - 1e-6 else 0.20)
        pads.add(pad([x + shift(a) for x in CHORDS[c][1]], b - a + 0.35, 1200.0 if a < H.start else 1800.0,
                     seed=int(a * 100)), a, gain=g,
                 until=NM.start, fade=STOPF)
    pads.add(pad(card_chord, tl.T - NM.start + a0 + 0.35, 900.0, seed=9), NM.start, gain=0.12)
    nh = ns(NM.dur + 0.6)
    th = np.arange(nh) / SR
    sub = np.sin(2 * np.pi * hz(card_sub) * th) + 0.3 * np.sin(4 * np.pi * hz(card_sub) * th)
    fx.add(sub * np.clip(th / 0.12, 0, 1) * np.exp(-th / 0.9), NM.start, gain=0.30)
    reg.add(NM.start, "groove (bass) stops at the name card (resolution, no impact)", "v2.bass", "stop")
    # drop before pass B: hiss swells +20 dB over the last 0.35 s
    nr = ns(0.35)
    tr = np.arange(nr) / SR
    hiss = circ_sos(hp(6000.0, 4), rng.standard_normal(nr)) * 10 ** ((-20.0 + 20.0 * tr / 0.35) / 20)
    fx.add(fade_edges(hiss, 0.005, 0.004), b0 - 0.35, gain=0.35)
    # hero: gated band-limited noise on 16ths on the second beat of every 2-beat interval
    for a, b in hero_iv:
        for t in grid(a + spb, b, spb / 4):
            ng = ns(0.05)
            gn = signal.sosfilt(bp(4500.0, 5500.0), rng.standard_normal(ng)) * np.exp(-np.arange(ng) / (0.012 * SR))
            fx.add(fade_edges(gn, 0.0005, 0.005), t, gain=0.12, pan=rng.uniform(-0.5, 0.5), until=NM.start,
                   fade=HIREL)
    kick_b.x *= 0.8
    drums.x *= 0.8
    bass.x *= 1.6
    arps.x *= 4.0
    pads.x *= 2.5
    dry = kick_b.x + drums.x + bass.x + arps.x + pads.x + fx.x
    # subtle stutter on the pass-A cuts after the first (30 ms = 7.5 ms slice x 4, sample-hold
    # / 4, 6-bit, 45 % wet); none in B and C, where cuts come every beat / half beat
    glitched = dry.copy()
    for c in [s.start for s in SA[1:]]:  # not on the hero cut: its downbeat lands clean
        i0 = int(round(c * SR))
        L, sl = ns(0.03), ns(0.0075)
        st = np.concatenate([fade_edges(dry[:, i0:i0 + sl], 0.0005, 0.0008)] * 4, axis=1)[:, :L]
        hold = np.repeat(st[:, ::4], 4, axis=1)[:, :L]
        pk = np.max(np.abs(hold)) + 1e-9
        crush = np.round(hold / pk * 31) / 31 * pk
        w = np.full(L, 0.45)
        nf = ns(0.003)
        w[:nf] *= ramp(nf)
        w[-nf:] *= ramp(nf)[::-1]
        glitched[:, i0:i0 + L] = dry[:, i0:i0 + L] * (1 - w) + crush * w
        reg.add(c, "stutter", "v2.glitch")
    ir = make_ir(8, 1.8, 2.6)
    wet = reverb(tl, 0.5 * arps.x.mean(0) + 0.6 * pads.x.mean(0) + 0.25 * fx.x.mean(0), ir, []) * 0.45
    layers = {"v2.kick": kick_b.x, "v2.drums": drums.x, "v2.bass": bass.x, "v2.arps": arps.x, "v2.pads": pads.x,
              "v2.fx": fx.x, "v2.glitch": glitched - dry, "v2.wet": wet}
    harmony = [(a, b, [x + shift(a) for x in CHORDS[c][1]]) for a, b, c in segs]
    harmony.append((NM.start, tl.T + a0, list(card_chord)))
    o["_harmony"] = harmony  # (start, end, chord tones) over the loop; the card chord runs across the seam
    o["_marks"] = {"a0": a0, "b0": b0, "c0": c0, "m0": m0, "H": H.start, "NM": NM.start, "CL": tl["close"].start,
                   "cc": cc, "spb": spb}
    return layers


