"""Synthesize the soundtrack candidates and the SFX layer for the hybrid bonding short video (DevLog-015).

Everything is generated by code (numpy / scipy, 48 kHz stereo, fixed seeds): no samples, no recordings. Timing comes
from media/hybrid-bonding-short/edit.json (fps, bpm, per-shot frames and beats) plus the event table EVENTS below
(seconds from shot start, read from scenes/*.notes.md and the scene code), so every cue follows a `retime`.

Versions (music stems; each mix = music + SFX):
  v1 "vowel"     formant-synthesized sung vowel (Rosenberg glottal source, vibrato, jitter, shimmer, aspiration,
                 5-formant cascade, oo -> oh -> ah over the video) stepping up E major pentatonic one degree per pitch
                 level on the cuts; sub-bass crescendo (~32 dB); pulse density 1.0 -> 0.5 -> 0.25 -> 0.125 s through
                 the passes and an accelerando in the hero; hard stop on the name card (reverb gated), vowel alone
                 on the tonic, soft sub under the card's atlas footnote, vowel glides back to the opening note when
                 the halves make contact in the close.
  v2 "synthetic" 120 bpm, E minor, sections from edit.json (pass A / B / C = shot ids l..a / l..b / l..c):
                 4-beat bars from the first pass-A cut, so the 2-beat open is a pickup and close + open form one
                 bar across the loop; chords Em C G D per bar; kick per beat in A and B, per half beat in C (every
                 cut), per quarter beat in M (quarter-beat shots: heavy on 8ths, light on the off-16ths, plus 16th
                 bass) so the low / background pulse doubles with the cut rate; the high foreground stays at the
                 pass-C rate in M: hats 8ths / 16ths / 32nds and arps 8ths / 16ths / accented 16ths in A / B / C+M,
                 all from the first content cut; clean kick downbeat on the hero cut; open: 47 Hz sub from the
                 close contact, chirp 47 -> 188 Hz with rising crackle while the halves split; saw bass; drop
                 before pass B (lows out for the last beat, hiss swell +20 dB in 0.35 s); hero: 2-beat intervals in
                 one style: kick and a long bass note on each interval's first beat (C, then D from the Cu contact),
                 dark 16th arps, gated 4.5-5.5 kHz noise on the second beat, released over 60 ms before the cut; name card: the groove releases (25 ms)
                 into an Em pad and an E1 sub swell (resolution, no impact). Subtle stutter (30 ms, 45 % wet) on
                 pass-A cuts only.
  v2_alt_A/B/C   the v2 groove plus one harmonic layer on a long build that tops out in the hero and peaks on the name
                 card (ramp_db; layer gain bisected so the card's loudest 400 ms sits 1.5 dB over the hero's, SFX levelled
                 against the groove): A additive vowel-like pad (harmonics 3 -> 40, tilt, /u/ -> /ɑ/ formants, brightness
                 opening on the card); B whole-step lift at pass C plus a voicing that grows upward, resolving on an
                 A major spread chord on the card; C E minor pentatonic stack thickening with each cut-rate doubling.
  v3 "material"  each pitch level is a struck free-free bar (Euler-Bernoulli mode ratios 1 : 2.757 : 5.404 : 8.933 :
                 13.344, beating mode doublets, frequency-dependent decay) at f = 82.41 Hz * (1000 um / pitch)^a,
                 a = ln 16 / ln 2500 = 0.3544, so 1 mm -> E2 and 0.4 um -> E6 (4 octaves). Fundamentals are quantized
                 to E minor pentatonic: the partials are inharmonic anyway, and unquantized fundamentals sit 25-75 cents
                 off the E drone and beat against it; quantization keeps the order, keeps both ends exact and moves no
                 level by more than 75 cents (printed by `events`). Pass A strikes one tone per cut over a sparse tock;
                 pass B restrikes 0.5 -> 0.0625 s; hero: damp, A4 at the Cu contact (sus4 = the gap), full chord with
                 A4 -> G#4 when the line is gone; name card: the 1 mm tone alone; close contact: the 0.4 um tone.
  sfx            boot (close contact + glow front, crackle across the seam) and split release (open), both soft
                 texture (40 ms thump attack, sparse crackle, -14 / -18 dB re music); underfill hiss plus a mokugyo
                 (wooden temple block) strike on each bump pin (l2a); TCB tock + press (l4a); reflow blips + thud
                 (l1b); anneal beating -> unison (E5 pair, re-attacked a whole tone lower at the middle of its
                 span, ~-5 dB re the E5 half and fading out by the cut)
                 + Cu-contact tick (hero; the bond-wave noise sweep was removed on the
                 owner's request, 2026-10-22). The end hit on the name card was removed (owner, 2026-10-22).
                 Event times are scene times divided by the shot's `speed` param. Shot-bound cues end at their cut;
                 cues that start after it (or too close to it) are dropped and logged.

Loop: every sound is either an enveloped event added circularly (indices mod N) or a contour oscillator whose phase is
made periodic (integer cycles over the loop); filters and reverbs run circularly. The last sample flows into the first.

Mastering: music stem normalized to -17 LUFS, SFX cues levelled per mix (CUE_TARGET_DB), mix gain to -16 LUFS integrated
(ITU-R BS.1770-4, own implementation), lookahead limiter on 4x-oversampled peaks at -1.5 dBTP; ffmpeg loudnorm
(analysis mode) re-measures every file. The SFX-only mix is normalized the same way (louder than inside the mixes).

Usage (every command takes --edit FILE, default media/hybrid-bonding-short/edit.json; outputs for edit_<x>.json
carry the suffix _<x>, e.g. mix_v2_exempt.wav, v2_synthetic_exempt.mp4, verify_exempt.json):
  uv run --no-project --with numpy --with scipy --with soundfile --with matplotlib python -I scripts/synth_audio.py events
      resolved event table (absolute times) and the v3 pitch -> frequency ladder; writes nothing
  uv run ... python -I scripts/synth_audio.py render [--only v1 v2 v3 sfx] [--no-verify]
      stems (32-bit float) + mixes (24-bit, mastered) -> cache/video/audio/: music_v{1,2,3}.wav, sfx.wav (design
      level), sfx_v{1,2,3}.wav (cues levelled per mix to CUE_TARGET_DB re that music), mix_v{1,2,3}.wav, mix_sfx.wav;
      verification (event timing on per-layer onsets / f0, loudness via ffmpeg, loop seam, SFX-vs-music levels,
      spectrograms spec_*.png) -> cache/video/audio/verify.json
  uv run ... python -I scripts/synth_audio.py compare --ref FILE [--ref-card 16.0] [--mixes mix_v2.wav ...]
      harmonic-build metrics (strong partials, tonal centroid / bandwidth, 400 ms loudness, band energies per quarter
      before the card, peak positions re the card) vs a reference -> cache/video/audio/compare_metrics.json,
      compare_spec.png, compare_curves.png (time axis aligned on each name card)
  uv run ... python -I scripts/synth_audio.py mux [--only v2 sfx v2_alt_A ...]
      mixes onto the draft MP4 (video stream copied, AAC 128k 48 kHz stereo, +faststart) ->
      media/hybrid-bonding-short/out/audio-eval/{v1_vowel,v2_synthetic,v3_material,sfx_only}.mp4;
      refuses when the video duration differs from edit.json by more than half a frame
  uv run ... python -I scripts/synth_audio.py all
      render + mux
Logs: logs/synth_audio_<timestamp>_<pid>.log.
"""

