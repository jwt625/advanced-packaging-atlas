def detect_onsets(x: np.ndarray, hop: int = 120, nfft: int = 1024) -> np.ndarray:
    """Spectral-flux onsets (s) of a loop, circular; frames are centred."""
    mono = x.mean(0) if x.ndim == 2 else x
    pad = nfft
    xx = np.concatenate([mono[-pad:], mono, mono[:pad]])
    nfr = (mono.size) // hop
    idx = pad + np.arange(nfr)[:, None] * hop + np.arange(nfft)[None, :] - nfft // 2
    win = np.hanning(nfft)
    mag = np.abs(np.fft.rfft(xx[idx] * win, axis=1))
    lm = np.log1p(1000.0 * mag / (mag.max() + 1e-12))
    flux = np.maximum(0, np.diff(lm, axis=0, prepend=lm[-1:])).sum(1)
    flux = np.roll(flux, 0)
    med = ndimage.median_filter(flux, size=int(0.2 * SR / hop) | 1, mode="wrap")
    thr = 1.5 * med + 0.04 * flux.max()
    loc = ndimage.maximum_filter1d(flux, size=int(0.015 * SR / hop) | 1, mode="wrap")
    pk = np.where((flux >= loc) & (flux > thr))[0]
    return pk * hop / SR


def f0_track(x: np.ndarray, fmin: float = 150.0, fmax: float = 900.0, hop: int = 240, win: int = 2048):
    mono = x.mean(0) if x.ndim == 2 else x
    xx = np.concatenate([mono[-win:], mono, mono[:win]])
    nfr = mono.size // hop
    idx = win + np.arange(nfr)[:, None] * hop + np.arange(win)[None, :] - win // 2
    fr = xx[idx] * np.hanning(win)
    spec = np.fft.rfft(fr, 2 * win, axis=1)
    ac = np.fft.irfft(np.abs(spec) ** 2, axis=1)[:, :win]
    ac /= ac[:, :1] + 1e-12
    lo, hi = int(SR / fmax), int(SR / fmin)
    seg = ac[:, lo:hi]
    k = np.argmax(seg, axis=1)
    kk = np.clip(k, 1, seg.shape[1] - 2)
    a, b, c = seg[np.arange(nfr), kk - 1], seg[np.arange(nfr), kk], seg[np.arange(nfr), kk + 1]
    off = 0.5 * (a - c) / (a - 2 * b + c + 1e-12)
    lag = lo + kk + np.clip(off, -1, 1)
    return np.arange(nfr) * hop / SR, SR / lag, b


def spectral_centroid(x: np.ndarray) -> float:
    sp = np.abs(np.fft.rfft(x * np.hanning(x.size)))
    fr = np.fft.rfftfreq(x.size, 1 / SR)
    return float((sp * fr).sum() / (sp.sum() + 1e-12))


def circ_err(d: float, t: float, T: float) -> float:
    return (d - t + T / 2) % T - T / 2


def verify_events(tl: TL, layers: dict[str, np.ndarray], reg: Reg) -> list[dict]:
    res = []
    on_cache: dict[str, np.ndarray] = {}
    f0_cache: dict[str, tuple] = {}
    for ev in reg.items:
        lay, kind = ev["layer"], ev["kind"]
        r = {**ev}
        if kind == "info":
            continue
        if kind == "onset":
            if lay not in on_cache:
                on_cache[lay] = detect_onsets(layers[lay])
            on = on_cache[lay]
            e = np.array([circ_err(d, ev["t"], tl.T) for d in on])
            j = int(np.argmin(np.abs(e)))
            r.update(found=round(float(on[j]), 4), err_ms=round(1000 * float(e[j]), 1))
        elif kind == "pitch":
            if lay not in f0_cache:
                f0_cache[lay] = f0_track(layers[lay])
            ts, f0, _ = f0_cache[lay]
            mid = (ev["m0"] + ev["m1"]) / 2
            mm = 69 + 12 * np.log2(np.maximum(f0, 1) / 440.0)
            sgn = np.sign(ev["m1"] - ev["m0"])
            w = np.where((ts > ev["t"] - 0.2) & (ts < ev["t"] + 0.2))[0]
            cross = None
            for a, b in zip(w[:-1], w[1:]):
                if (mm[a] - mid) * sgn < 0 <= (mm[b] - mid) * sgn:
                    fa = (mid - mm[a]) / (mm[b] - mm[a])
                    cross = ts[a] + fa * (ts[b] - ts[a])
                    break
            r.update(found=None if cross is None else round(float(cross), 4),
                     err_ms=None if cross is None else round(1000 * (cross - ev["t"]), 1))
        elif kind == "stop":
            m = layers[lay].mean(0)
            e = np.sqrt(np.maximum(ndimage.uniform_filter1d(m ** 2, ns(0.005), mode="wrap"), 0))
            i = int(ev["t"] * SR)
            pre = float(np.mean(e[i - ns(0.2): i - ns(0.01)]))
            post = e[i - ns(0.05): i + ns(0.4)]
            hold = ndimage.maximum_filter1d(post, ns(0.15), origin=-(ns(0.15) // 2))  # max over the next 150 ms
            k = np.where(hold[: post.size - ns(0.15)] < pre * 0.1)[0]  # level stays below -20 dB for 150 ms
            tt = (i - ns(0.05) + k[0]) / SR if k.size else None
            r.update(found=None if tt is None else round(tt, 4), err_ms=None if tt is None else round(1000 * (tt - ev["t"]), 1),
                     drop_db=round(20 * np.log10(pre / (np.mean(e[i + ns(0.03): i + ns(0.1)]) + 1e-12)), 1))
        elif kind == "press":
            y = layers[lay].mean(0)
            def fpk(t0: float) -> float:
                seg = y[int(t0 * SR): int(t0 * SR) + ns(0.2)] * np.hanning(ns(0.2))
                sp = np.abs(np.fft.rfft(seg, 2 ** 19))
                fr = np.fft.rfftfreq(2 ** 19, 1 / SR)
                band = (fr > 60) & (fr < 120)
                return float(fr[band][np.argmax(sp[band])])
            r.update(f_start=round(fpk(ev["t"] + 0.03), 1), f_end=round(fpk(ev["t_end"] - 0.2), 1))
            on = detect_onsets(layers[lay])
            e = np.array([circ_err(d, ev["t"], tl.T) for d in on]) if on.size else np.array([np.inf])
            j = int(np.argmin(np.abs(e)))
            r.update(err_ms=round(1000 * float(e[j]), 1) if np.isfinite(e[j]) else None)
        elif kind == "pan":
            y = layers[lay]
            i0 = int(ev["t"] * SR)
            sl = slice(i0 + ns(0.05), i0 + ns(0.6))
            el = ndimage.uniform_filter1d(y[0, sl] ** 2, ns(0.02))
            er = ndimage.uniform_filter1d(y[1, sl] ** 2, ns(0.02))
            bal = (er - el) / (er + el + 1e-12)
            k = np.where(np.diff(np.sign(bal)) > 0)[0]
            tmid = ev["t"] + 0.05 + (k[0] / SR if k.size else np.nan)
            r.update(found=round(float(tmid), 4), err_ms=round(1000 * (tmid - ev["t_mid"]), 1), label=r["label"] +
                     " (pan crosses centre vs front mid-frame)", t=ev["t_mid"])
        elif kind == "decay":
            y = layers[lay]
            i = int(ev["t"] * SR)
            e = np.sqrt(np.maximum(ndimage.uniform_filter1d((y[:, i - ns(0.01): i + ns(0.3)] ** 2).sum(0), ns(0.004)), 0))
            e0 = e.max()
            k = int(np.argmax(e))
            at = e[k + ns(0.2)] if k + ns(0.2) < e.size else e[-1]
            r.update(decay_db_in_0p2s=round(float(20 * np.log10(e0 / (at + 1e-12))), 1),
                     centroid_hz=round(spectral_centroid(y[:, i: i + ns(0.05)].mean(0)), 0))
        elif kind == "unison":
            y = layers[lay].mean(0)
            env = np.abs(signal.hilbert(y[int(ev["t_start"] * SR): int((ev["t"] + 0.6) * SR)]))
            env = ndimage.uniform_filter1d(env, ns(0.01))
            ts = ev["t_start"] + np.arange(env.size) / SR
            mins = signal.argrelmin(env, order=ns(0.02))[0]
            mins = mins[(ts[mins] > ev["t_start"] + 0.2) & (env[mins] < 0.6 * np.median(env))]
            mins = mins[ts[mins] < ev["t"]]
            after = env[(ts > ev["t"]) & (ts < ev["t"] + 0.28)]
            mod_db = 20 * np.log10(after.max() / (after.min() + 1e-12)) if after.size else None
            pre = env[(ts > ev["t"] - 0.28) & (ts < ev["t"])]
            r.update(beat_nulls=[round(float(ts[m]), 3) for m in mins],
                     beat_periods_s=[round(float(x), 3) for x in np.diff(ts[mins])],
                     env_ripple_last_0p28s_before_db=round(float(20 * np.log10(pre.max() / (pre.min() + 1e-12))), 2),
                     env_ripple_0p28s_after_db=None if mod_db is None else round(float(mod_db), 2))
        res.append(r)
    return res


def seam_check(x: np.ndarray) -> dict:
    d = np.abs(np.diff(x, axis=1))
    seam = float(np.max(np.abs(x[:, 0] - x[:, -1])))
    w = ns(0.05)
    local = float(np.max(np.concatenate([d[:, :w], d[:, -w:]], axis=1)))
    d2 = np.abs(np.diff(np.concatenate([x[:, -w:], x[:, :w]], axis=1), 2, axis=1))
    i = w - 1
    seam2 = float(np.max(d2[:, i - 2: i + 2]))
    local2 = float(np.percentile(d2, 99.9))
    return {"seam_step": seam, "max_step_within_50ms": local, "seam_d2": seam2, "p99_9_d2_within_50ms": local2,
            "click_free": bool(seam <= local * 1.0 + 1e-9 and seam2 <= max(local2 * 2, 1e-6))}


