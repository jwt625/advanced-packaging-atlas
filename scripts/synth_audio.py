def hz(midi: float | np.ndarray) -> float | np.ndarray:
    return 440.0 * 2.0 ** ((np.asarray(midi) - 69.0) / 12.0)


NOTE = ["C", "C#", "D", "D#", "E", "F", "F#", "G", "G#", "A", "A#", "B"]


def note_name(m: int) -> str:
    return f"{NOTE[m % 12]}{m // 12 - 1}"


def ns(sec: float) -> int:
    return max(1, int(round(sec * SR)))


def periodic(tl: TL, pts: list[tuple[float, float]]) -> np.ndarray:
    """Piecewise-linear contour through (time, value) points, periodic over the loop."""
    xs = np.array([p[0] for p in pts]) % tl.T
    ys = np.array([p[1] for p in pts], float)
    return np.interp(tl.t, xs, ys, period=tl.T)


def steps(tl: TL, changes: list[tuple[float, float]], glide: float) -> np.ndarray:
    """Step contour: value changes at each time with a linear glide centred on it (periodic)."""
    changes = sorted(changes)
    pts = []
    for i, (tc, v) in enumerate(changes):
        prev = changes[i - 1][1]
        if prev == v:
            continue
        pts += [(tc - glide / 2, prev), (tc + glide / 2, v)]
    if not pts:
        return np.full(tl.N, changes[0][1], float)
    return periodic(tl, pts)


def periodic_phase(f: np.ndarray) -> np.ndarray:
    """Phase in cycles for a frequency contour, scaled (< 1 cycle over the loop) to an integer number of cycles."""
    c = f.sum() / SR
    f = f * (max(1.0, round(c)) / c)
    ph = np.cumsum(f) / SR
    return ph - ph[0]


def smooth_noise(rng: np.random.Generator, n: int, fc: float) -> np.ndarray:
    x = rng.standard_normal(n)
    y = circ_sos(lp(fc, 2), x)
    return y / (np.std(y) + 1e-12)


@functools.lru_cache(maxsize=512)
def lp(fc: float, order: int = 2) -> np.ndarray:
    return signal.butter(order, min(fc, 0.45 * SR), btype="low", fs=SR, output="sos")


@functools.lru_cache(maxsize=512)
def hp(fc: float, order: int = 2) -> np.ndarray:
    return signal.butter(order, fc, btype="high", fs=SR, output="sos")


@functools.lru_cache(maxsize=512)
def bp(f1: float, f2: float, order: int = 2) -> np.ndarray:
    return signal.butter(order, [f1, min(f2, 0.45 * SR)], btype="band", fs=SR, output="sos")


def circ_sos(sos: np.ndarray, x: np.ndarray, pre: float = 0.5) -> np.ndarray:
    """Steady-state circular filtering: prepend the loop's last `pre` seconds, filter, drop them."""
    m = min(ns(pre), x.shape[-1])
    xx = np.concatenate([x[..., -m:], x], axis=-1)
    return signal.sosfilt(sos, xx, axis=-1)[..., m:]


def circ_conv(x: np.ndarray, ir: np.ndarray) -> np.ndarray:
    """Circular convolution of a mono loop with a stereo IR -> (2, N)."""
    n = x.shape[0]
    out = np.zeros((2, n))
    for c in range(2):
        y = signal.fftconvolve(x, ir[c])
        out[c] = y[:n]
        tail = y[n:]
        while tail.size:
            k = min(n, tail.size)
            out[c, :k] += tail[:k]
            tail = tail[k:]
    return out


def make_ir(seed: int, t60: float, dur: float, bright_tau: float = 0.2, predelay: float = 0.012) -> np.ndarray:
    rng = np.random.default_rng(seed)
    n = ns(dur)
    t = np.arange(n) / SR
    raw = rng.standard_normal((2, n)) * np.exp(-6.91 * t / t60)
    dark = signal.sosfilt(lp(2500.0), raw, axis=1)
    w = np.exp(-t / bright_tau)
    ir = raw * w + dark * (1 - w)
    ir[:, : ns(predelay)] = 0.0
    return ir / np.sqrt((ir ** 2).sum() / 2)


def pan2(x: np.ndarray, pan: float | np.ndarray) -> np.ndarray:
    th = (np.clip(pan, -1, 1) + 1) * np.pi / 4
    return np.stack([x * np.cos(th), x * np.sin(th)])


def ramp(n: int) -> np.ndarray:
    return 0.5 - 0.5 * np.cos(np.pi * np.arange(n) / max(n, 1))


def fade_edges(x: np.ndarray, a: float, r: float) -> np.ndarray:
    na, nr = min(ns(a), x.shape[-1]), min(ns(r), x.shape[-1])
    x = x.copy()
    x[..., :na] *= ramp(na)
    x[..., x.shape[-1] - nr:] *= ramp(nr)[::-1]
    return x


def polyblep(p: np.ndarray, dt: np.ndarray) -> np.ndarray:
    out = np.zeros_like(p)
    m = p < dt
    x = p[m] / dt[m]
    out[m] = x + x - x * x - 1
    m = p > 1 - dt
    x = (p[m] - 1) / dt[m]
    out[m] = x * x + x + x + 1
    return out


def saw(ph: np.ndarray, f: np.ndarray) -> np.ndarray:
    p = ph % 1.0
    return 2 * p - 1 - polyblep(p, np.broadcast_to(f / SR, p.shape))


def pulse(ph: np.ndarray, f: np.ndarray, duty: float) -> np.ndarray:
    return 0.5 * (saw(ph, f) - saw(ph + duty, f))


class Bus:
    """Stereo loop buffer; events are added circularly."""

    def __init__(self, tl: TL) -> None:
        self.N = tl.N
        self.x = np.zeros((2, tl.N))

    def add(self, sig: np.ndarray, t0: float, gain: float = 1.0, pan: float = 0.0, until: float | None = None,
            fade: float = 0.006) -> None:
        sig = np.asarray(sig, float)
        if sig.ndim == 1:
            sig = pan2(sig, pan)
        if until is not None:
            m = int(round((until - t0) * SR))
            if m <= 0:
                return
            if m < sig.shape[1]:
                sig = sig[:, :m].copy()
                nf = min(ns(fade), m)
                sig[:, m - nf:] *= ramp(nf)[::-1]
        n = min(sig.shape[1], self.N)
        i0 = int(round(t0 * SR)) % self.N
        first = min(n, self.N - i0)
        self.x[:, i0:i0 + first] += gain * sig[:, :first]
        if n > first:
            self.x[:, : n - first] += gain * sig[:, first:n]


@dataclass
class Reg:
    """Scheduled events for verification: (time, label, layer, kind, extra)."""

    items: list[dict] = field(default_factory=list)

    def add(self, t: float, label: str, layer: str, kind: str = "onset", **kw: object) -> None:
        self.items.append({"t": float(t), "label": label, "layer": layer, "kind": kind, **kw})


