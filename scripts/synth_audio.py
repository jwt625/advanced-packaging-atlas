    ax.set_yscale("log")
    ax.set_ylim(20, 20000)
    ax.set_ylabel("Hz", color="#9aa4ad")
    e = np.sqrt(np.maximum(ndimage.uniform_filter1d(mono ** 2, ns(0.01)), 0))
