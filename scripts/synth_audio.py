    L: dict[str, Bus] = {k: Bus(tl) for k in ("boot", "split", "uf_hiss", "uf_ticks", "tcb_tock", "tcb_press", "blips",
                                               "thud", "anneal", "hero_tick")}
    MIN_CUE = 0.15  # a continuous cue that would get less than this before its shot's cut is dropped

    def cut(sid: str) -> float:
        return tl.es(sid).end

    def fits(sid: str, t0: float, label: str, min_len: float = 0.0) -> bool:
        if t0 + min_len < cut(sid) - 1e-9:
            return True
        log(f"WARNING {label} at {t0:.3f} s does not fit before the {sid} cut ({cut(sid):.3f} s); dropped")
        return False
    # 1 boot (split-horizon loop): 47 Hz thump when the halves make contact in the close (the line appears), a
    # 50 -> 200 Hz chirp under the left-to-right glow front, 3-7 kHz crackle thinning out over ~1.2 s across the seam;
    # in the open, a soft airy release while the halves pull apart
    CL = tl["close"]
    t0 = tl.ev("close", "contact")
    tfe = tl.ev("close", "front_end")
    n = ns(0.9)
    t = np.arange(n) / SR
    thump = np.sin(2 * np.pi * np.cumsum(47.0 + 8.0 * np.exp(-t / 0.03)) / SR) * np.exp(-t / 0.18)
    L["boot"].add(fade_edges(thump, 0.04, 0.05), t0, gain=0.17)
    reg.add(t0, "boot thump (close contact)", "sfx.boot")
    dch = max(tfe - t0, 0.2) + 0.15
    nc = ns(dch)
    tc = np.arange(nc) / SR
    fch = 50.0 * 4.0 ** np.clip(tc / (dch - 0.15), 0, 1)
    chirp = np.sin(2 * np.pi * np.cumsum(fch) / SR) * np.sin(np.pi * np.clip(tc / dch, 0, 1)) ** 3
    xf = close_front_x(tl, (t0 - CL.start) + tc)
    L["boot"].add(pan2(chirp, np.clip(xf / 960.0 - 1.0, -0.8, 0.8) * 0.5), t0, gain=0.05)
    tt = 0.0
    while tt < 1.2:
        rate = 12.0 * np.exp(-tt / 0.4)
        tt += rng.exponential(1.0 / max(rate, 1.0))
        if tt >= 1.2:
            break
        m = ns(rng.uniform(0.0005, 0.0015))
        c = signal.sosfilt(bp(3000.0, 7000.0), rng.standard_normal(m + 64))[64:] * np.hanning(m)
        L["boot"].add(c, t0 + tt, gain=0.03 * rng.uniform(0.3, 1.0) * np.exp(-tt / 0.6), pan=rng.uniform(-0.5, 0.5))
    ts, tsd = tl.ev("open", "split"), tl.ev("open", "split_done")
    m = ns(tsd - ts + 0.06)
    tk = np.arange(m) / SR
    nz = signal.sosfilt(bp(300.0, 2500.0), rng.standard_normal((2, m)), axis=1)
    uu = np.clip(tk / (tsd - ts), 0, 1)
    wenv = uu ** 1.5 * np.clip((tsd - ts + 0.06 - tk) / 0.12, 0, 1)
    L["split"].add(fade_edges(nz * wenv, 0.05, 0.04), ts, gain=0.035)
    reg.add(ts, "open split release", "sfx.split", "info")
    # 2 underfill: hiss lowpass 800 -> 3000 Hz with the front, panned with it; soft tick at each pin
    s = tl.es("l2a")
    fx = EVENTS["l2a"]["front_x"]  # type: ignore[index]
    t_end = min(s.dur, float(EVENTS["l2a"]["front_exit"]) / s.speed)  # type: ignore[arg-type]
    n = ns(t_end)
    t = np.arange(n) / SR
    x = np.interp(t * s.speed, [p[0] for p in fx], [p[1] for p in fx])
    u = np.clip((x - 240.0) / (1980.0 - 240.0), 0, 1)
    fc = 800.0 * (3000.0 / 800.0) ** u
    nz = signal.sosfilt(hp(250.0), rng.standard_normal(n))
    hiss = np.zeros(n)
    blk = 480
    zi = np.zeros((2, 2))
    for i0 in range(0, n, blk):
        sos = lp(float(round(fc[min(i0 + blk // 2, n - 1)] / 25) * 25), 4)
        hiss[i0:i0 + blk], zi = signal.sosfilt(sos, nz[i0:i0 + blk], zi=zi)
    hiss *= 1 + 0.35 * smooth_noise(rng, n, 6.0) * 0.5
    hiss = fade_edges(hiss, 0.12, 0.03)
    L["uf_hiss"].add(pan2(hiss, np.clip(x / 960.0 - 1.0, -0.8, 0.8) * 0.8), s.start, gain=0.06)
    # one mokugyo (wooden-fish temple block) strike per bump pin (owner, 2026-10-22); two block sizes alternate
    for i, tp in enumerate(tl.evs("l2a", "pins")):
        xp = float(np.interp((tp - s.start) * s.speed, [p[0] for p in fx], [p[1] for p in fx]))
        tok = mokugyo(rng, 430.0 if i % 2 == 0 else 610.0, 1.0 if i % 2 == 0 else 0.8)
        if fits("l2a", tp, "underfill mokugyo strike", 0.01):
            L["uf_ticks"].add(tok, tp, gain=0.30, pan=float(np.clip(xp / 960 - 1, -0.8, 0.8)) * 0.6, until=cut("l2a"),
                              fade=0.02)
            reg.add(tp, "underfill mokugyo strike", "sfx.uf_ticks")
    # 3 TCB: chalk tock at contact (~1.2 kHz band, 40 ms), 90 Hz press sagging 10 % over the collapse
    tct = tl.ev("l4a", "contact")
    m = ns(0.04)
    tk = np.arange(m) / SR
    tockx = (signal.sosfilt(bp(850.0, 1700.0, 2), rng.standard_normal(m)) * np.exp(-tk / 0.007)
             + 0.6 * np.sin(2 * np.pi * 1200 * tk) * np.exp(-tk / 0.008))
    if fits("l4a", tct, "TCB contact tock", 0.01):
        L["tcb_tock"].add(fade_edges(tockx, 0.0003, 0.006), tct, gain=0.6, pan=0.0, until=cut("l4a"))
        reg.add(tct, "TCB contact tock", "sfx.tcb_tock")
    t1, t2 = tl.ev("l4a", "melt"), tl.ev("l4a", "settled")
    m = ns(t2 - t1 + 0.12)
    tk = np.arange(m) / SR
    sag = np.clip(tk / (t2 - t1), 0, 1)
    fp = 90.0 * (1 - 0.10 * sag * sag * (3 - 2 * sag))
    press = np.sin(2 * np.pi * np.cumsum(fp) / SR) + 0.25 * np.sin(4 * np.pi * np.cumsum(fp) / SR)
    if fits("l4a", t1, "TCB press (collapse)", MIN_CUE):
        L["tcb_press"].add(fade_edges(press, 0.03, 0.12), t1, gain=0.12, until=cut("l4a"), fade=0.03)
        if t2 <= cut("l4a"):
            reg.add(t1, "TCB press start", "sfx.tcb_press", "press", f0=90.0, f1=81.0, t_end=t2)
    # 4 reflow: 8-bit square blips, one per ball, stepped pitch drop; 60 Hz thud at the package collapse
    pent = [76, 79, 81, 83, 86, 88, 91, 93]
    for i, tb in enumerate(tl.evs("l1b", "melts")):
        m = ns(0.045)
        tk = np.arange(m) / SR
        f = hz(pent[i]) * np.where(tk < 0.015, 1.0, np.where(tk < 0.03, 2 ** (-3 / 12), 2 ** (-7 / 12)))
        sq = np.sign(np.sin(2 * np.pi * np.cumsum(f) / SR))
        sq = np.round(sq * np.exp(-tk / 0.03) * 7) / 7
        if fits("l1b", tb, f"reflow blip {i + 1}", 0.01):
            L["blips"].add(fade_edges(sq, 0.0004, 0.004), tb, gain=0.07, pan=-0.6 + 1.2 * i / 7, until=cut("l1b"))
            reg.add(tb, f"reflow blip {i + 1}", "sfx.blips")
    tcol, tset = tl.ev("l1b", "collapse"), tl.ev("l1b", "settled")
    m = ns(tset - tcol + 0.15)
    tk = np.arange(m) / SR
    thud = np.sin(2 * np.pi * np.cumsum(60.0 + 25 * np.exp(-tk / 0.012)) / SR) * np.exp(-tk / 0.07)
    thud += signal.sosfilt(lp(400.0), rng.standard_normal(m)) * np.exp(-tk / 0.02) * 0.3
    if fits("l1b", tcol, "reflow collapse thud", 0.05):
        L["thud"].add(fade_edges(thud, 0.001, 0.03), tcol, gain=0.35, until=cut("l1b"), fade=0.02)
        reg.add(tcol, "reflow collapse thud", "sfx.thud")
    H = tl["hero"]
    # 5b anneal: two tones 6 Hz apart converging to unison when the line is gone; tick at the Cu contact
    ta, tg, tcu = tl.ev("hero", "anneal"), tl.ev("hero", "line_gone"), tl.ev("hero", "cu_contact")
    # The pair is split in two halves (owner, 2026-10-22): E5 from the anneal start, re-attacked a whole tone lower
    # (D5) at the 8th-note grid point nearest the middle of its span; the 6 Hz -> 0 detune runs on unchanged, so the
    # unison (both tones in phase) still lands when the line is gone.
    m = ns(tg - ta + 1.3)
    tk = np.arange(m) / SR
    uu = np.clip(tk / (tg - ta), 0, 1)
    df = 6.0 * (1 - uu * uu * (3 - 2 * uu))
    ig = ns(tg - ta) - 1
    g8 = tl.section("a")[0].beat_t if tl.section("a") else tl.grid0
    t_end = min(cut("hero"), ta + tk[-1])
    t_split = g8 + round(((ta + t_end) / 2 - g8) / (tl.spb / 2)) * (tl.spb / 2)
    i_s = int(round((t_split - ta) * SR))

    def pair(f0: float) -> np.ndarray:
        p1 = np.cumsum(np.full(m, f0)) / SR
        p2 = np.cumsum(f0 + df) / SR
        p2 = p2 - ((p2[ig] - p1[ig]) % 1.0)  # in phase exactly at unison: the beating ends on a maximum
        return (np.sin(2 * np.pi * p1) + np.sin(2 * np.pi * p2)
                + 0.15 * (np.sin(4 * np.pi * p1) + np.sin(4 * np.pi * p2)))

    hold = 0.3
    aenv = np.clip(tk / 0.2, 0, 1) * np.where(tk < tg - ta + hold, 1.0, np.exp(-(tk - (tg - ta + hold)) / 0.3))
    w1 = np.clip((i_s - np.arange(m)) / ns(0.012), 0, 1)           # first half: 12 ms release at the split
    w2 = np.clip((np.arange(m) - i_s) / ns(0.005), 0, 1)           # second half: 5 ms re-attack
    # second half quieter and fading (owner, 2026-10-22): -7.5 dB gain at the re-attack (the near-unison pair sums
    # ~3 dB above the beating E5 average, so it measures ~-5 dB re the E5 half), -14 dB at the start of the hero's
    # last beat, -30 dB at the name-card cut (linear in dB between)
    t_last = cut("hero") - tl.spb
    d_db = np.interp(ta + tk, [t_split, t_last, cut("hero")], [-7.5, -14.0, -30.0])
    y = pair(659.2551) * w1 + pair(659.2551 * 2 ** (-2 / 12)) * w2 * 10 ** (d_db / 20)
    # organ version (owner, 2026-10-23): no anneal tone at all; the background organ ramp carries the hero
    if not organ:
        L["anneal"].add(fade_edges(y * aenv, 0.01, 0.1), ta, gain=0.14, until=cut("hero"), fade=0.05)
        reg.add(tg, "anneal unison", "sfx.anneal", "unison", t_start=ta)
        reg.add(t_split, "anneal re-attack a whole tone lower (E5 -> D5)", "sfx.anneal")
    m = ns(0.02)
    tk = np.arange(m) / SR
    tick = np.sin(2 * np.pi * 5200 * tk) * np.exp(-tk / 0.003) + 0.4 * signal.sosfilt(
        hp(4000.0), rng.standard_normal(m)) * np.exp(-tk / 0.0008)
    L["hero_tick"].add(fade_edges(tick, 0.0002, 0.003), tcu, gain=0.25, until=cut("hero"))
    reg.add(tcu, "Cu contact tick", "sfx.hero_tick")
    return {f"sfx.{k}": b.x for k, b in L.items()}


